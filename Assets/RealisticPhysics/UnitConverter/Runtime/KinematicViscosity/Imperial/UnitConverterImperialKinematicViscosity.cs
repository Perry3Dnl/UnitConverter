namespace RealisticPhysics.UnitConversion.KinematicViscosity.Imperial
{
    public static class UnitConverterImperialKinematicViscosity
    {
        public static double SquareFootPerSecondToSquareMeterPerSecond(double value)
        {
            return value * 0.092903040000000006d;
        }

        public static double SquareMeterPerSecondToSquareFootPerSecond(double baseValue)
        {
            return baseValue / 0.092903040000000006d;
        }

        public static double SquareInchPerSecondToSquareMeterPerSecond(double value)
        {
            return value * 0.00064515999999999998d;
        }

        public static double SquareMeterPerSecondToSquareInchPerSecond(double baseValue)
        {
            return baseValue / 0.00064515999999999998d;
        }

        public static double SquareFootPerMinuteToSquareMeterPerSecond(double value)
        {
            return value * 0.0015483840000000001d;
        }

        public static double SquareMeterPerSecondToSquareFootPerMinute(double baseValue)
        {
            return baseValue / 0.0015483840000000001d;
        }

        public static double SquareFootPerHourToSquareMeterPerSecond(double value)
        {
            return value * 2.5806400000000001e-05d;
        }

        public static double SquareMeterPerSecondToSquareFootPerHour(double baseValue)
        {
            return baseValue / 2.5806400000000001e-05d;
        }

        public static double SquareInchPerMinuteToSquareMeterPerSecond(double value)
        {
            return value * 1.0752666666666666e-05d;
        }

        public static double SquareMeterPerSecondToSquareInchPerMinute(double baseValue)
        {
            return baseValue / 1.0752666666666666e-05d;
        }

        public static double SquareInchPerHourToSquareMeterPerSecond(double value)
        {
            return value * 1.7921111111111112e-07d;
        }

        public static double SquareMeterPerSecondToSquareInchPerHour(double baseValue)
        {
            return baseValue / 1.7921111111111112e-07d;
        }

        public static double SquareYardPerSecondToSquareMeterPerSecond(double value)
        {
            return value * 0.83612735999999999d;
        }

        public static double SquareMeterPerSecondToSquareYardPerSecond(double baseValue)
        {
            return baseValue / 0.83612735999999999d;
        }

        public static double SquareYardPerMinuteToSquareMeterPerSecond(double value)
        {
            return value * 0.013935456000000001d;
        }

        public static double SquareMeterPerSecondToSquareYardPerMinute(double baseValue)
        {
            return baseValue / 0.013935456000000001d;
        }
    }

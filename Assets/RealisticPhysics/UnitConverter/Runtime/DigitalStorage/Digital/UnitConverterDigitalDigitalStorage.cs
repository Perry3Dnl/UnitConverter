namespace RealisticPhysics.UnitConversion.DigitalStorage.Digital
{
    public static class UnitConverterDigitalDigitalStorage
    {
        public static double BitToByte(double value)
        {
            return value * 0.125d;
        }

        public static double ByteToBit(double baseValue)
        {
            return baseValue / 0.125d;
        }

        public static double NibbleToByte(double value)
        {
            return value * 0.5d;
        }

        public static double ByteToNibble(double baseValue)
        {
            return baseValue / 0.5d;
        }

        public static double ByteToByte(double value)
        {
            return value;
        }

        public static double KilobitToByte(double value)
        {
            return value * 125.0d;
        }

        public static double ByteToKilobit(double baseValue)
        {
            return baseValue / 125.0d;
        }

        public static double KilobyteToByte(double value)
        {
            return value * 1000.0d;
        }

        public static double ByteToKilobyte(double baseValue)
        {
            return baseValue / 1000.0d;
        }

        public static double MegabitToByte(double value)
        {
            return value * 125000.0d;
        }

        public static double ByteToMegabit(double baseValue)
        {
            return baseValue / 125000.0d;
        }

        public static double MegabyteToByte(double value)
        {
            return value * 1000000.0d;
        }

        public static double ByteToMegabyte(double baseValue)
        {
            return baseValue / 1000000.0d;
        }

        public static double GigabitToByte(double value)
        {
            return value * 125000000.0d;
        }

        public static double ByteToGigabit(double baseValue)
        {
            return baseValue / 125000000.0d;
        }

        public static double GigabyteToByte(double value)
        {
            return value * 1000000000.0d;
        }

        public static double ByteToGigabyte(double baseValue)
        {
            return baseValue / 1000000000.0d;
        }

        public static double TerabitToByte(double value)
        {
            return value * 125000000000.0d;
        }

        public static double ByteToTerabit(double baseValue)
        {
            return baseValue / 125000000000.0d;
        }

        public static double TerabyteToByte(double value)
        {
            return value * 1000000000000.0d;
        }

        public static double ByteToTerabyte(double baseValue)
        {
            return baseValue / 1000000000000.0d;
        }

        public static double PetabyteToByte(double value)
        {
            return value * 1000000000000000.0d;
        }

        public static double ByteToPetabyte(double baseValue)
        {
            return baseValue / 1000000000000000.0d;
        }

        public static double KibibitToByte(double value)
        {
            return value * 128.0d;
        }

        public static double ByteToKibibit(double baseValue)
        {
            return baseValue / 128.0d;
        }

        public static double KibibyteToByte(double value)
        {
            return value * 1024.0d;
        }

        public static double ByteToKibibyte(double baseValue)
        {
            return baseValue / 1024.0d;
        }

        public static double MebibitToByte(double value)
        {
            return value * 131072.0d;
        }

        public static double ByteToMebibit(double baseValue)
        {
            return baseValue / 131072.0d;
        }

        public static double MebibyteToByte(double value)

namespace RealisticPhysics.UnitConversion.MassFlowRate.Imperial
{
    public static class UnitConverterImperialMassFlowRate
    {
        public static double PoundPerSecondToKilogramPerSecond(double value)
        {
            return value * 0.45359237000000002d;
        }

        public static double KilogramPerSecondToPoundPerSecond(double baseValue)
        {
            return baseValue / 0.45359237000000002d;
        }

        public static double PoundPerMinuteToKilogramPerSecond(double value)
        {
            return value * 0.0075598728333333334d;
        }

        public static double KilogramPerSecondToPoundPerMinute(double baseValue)
        {
            return baseValue / 0.0075598728333333334d;
        }

        public static double PoundPerHourToKilogramPerSecond(double value)
        {
            return value * 0.00012599788055555556d;
        }

        public static double KilogramPerSecondToPoundPerHour(double baseValue)
        {
            return baseValue / 0.00012599788055555556d;
        }

        public static double OuncePerSecondToKilogramPerSecond(double value)
        {
            return value * 0.028349523125000001d;
        }

        public static double KilogramPerSecondToOuncePerSecond(double baseValue)
        {
            return baseValue / 0.028349523125000001d;
        }

        public static double PoundPerDayToKilogramPerSecond(double value)
        {
            return value * 5.2499116898148151e-06d;
        }

        public static double KilogramPerSecondToPoundPerDay(double baseValue)
        {
            return baseValue / 5.2499116898148151e-06d;
        }

        public static double OuncePerMinuteToKilogramPerSecond(double value)
        {
            return value * 0.00047249205208333334d;
        }

        public static double KilogramPerSecondToOuncePerMinute(double baseValue)
        {
            return baseValue / 0.00047249205208333334d;
        }

        public static double SlugPerSecondToKilogramPerSecond(double value)
        {
            return value * 14.59390294d;
        }

        public static double KilogramPerSecondToSlugPerSecond(double baseValue)
        {
            return baseValue / 14.59390294d;
        }

        public static double SlugPerMinuteToKilogramPerSecond(double value)
        {
            return value * 0.24323171566666665d;
        }

        public static double KilogramPerSecondToSlugPerMinute(double baseValue)
        {
            return baseValue / 0.24323171566666665d;
        }
    }
}

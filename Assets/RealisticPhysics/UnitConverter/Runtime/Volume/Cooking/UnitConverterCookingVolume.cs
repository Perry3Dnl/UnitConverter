namespace RealisticPhysics.UnitConversion.Volume.Cooking
{
    public static class UnitConverterCookingVolume
    {
        public static double MetricTeaspoonToLiter(double value)
        {
            return value * 0.0050000000000000001d;
        }

        public static double LiterToMetricTeaspoon(double baseValue)
        {
            return baseValue / 0.0050000000000000001d;
        }

        public static double MetricTablespoonToLiter(double value)
        {
            return value * 0.014999999999999999d;
        }

        public static double LiterToMetricTablespoon(double baseValue)
        {
            return baseValue / 0.014999999999999999d;
        }

        public static double MetricCupToLiter(double value)
        {
            return value * 0.25d;
        }

        public static double LiterToMetricCup(double baseValue)
        {
            return baseValue / 0.25d;
        }

        public static double DashToLiter(double value)
        {
            return value * 0.00061611519921874998d;
        }

        public static double LiterToDash(double baseValue)
        {
            return baseValue / 0.00061611519921874998d;
        }

        public static double PinchToLiter(double value)
        {
            return value * 0.00030805759960937499d;
        }

        public static double LiterToPinch(double baseValue)
        {
            return baseValue / 0.00030805759960937499d;
        }

        public static double USShotToLiter(double value)
        {
            return value * 0.044360294343750002d;
        }

        public static double LiterToUSShot(double baseValue)
        {
            return baseValue / 0.044360294343750002d;
        }

        public static double ImperialShotToLiter(double value)
        {
            return value * 0.035516328125000003d;
        }

        public static double LiterToImperialShot(double baseValue)
        {
            return baseValue / 0.035516328125000003d;
        }

        public static double USDessertSpoonToLiter(double value)
        {
            return value * 0.0098578431874999997d;
        }

        public static double LiterToUSDessertSpoon(double baseValue)
        {
            return baseValue / 0.0098578431874999997d;
        }

        public static double ImperialDessertSpoonToLiter(double value)
        {
            return value * 0.011838776041666671d;
        }

        public static double LiterToImperialDessertSpoon(double baseValue)
        {
            return baseValue / 0.011838776041666671d;
        }
    }
}

namespace UnitTools.Inductance.Metric
{
    public static class UnitToolsMetricInductance
    {
        public static double NanohenryToHenry(double value)
        {
            return value * 1.0000000000000001e-09d;
        }

        public static double HenryToNanohenry(double baseValue)
        {
            return baseValue / 1.0000000000000001e-09d;
        }

        public static double MicrohenryToHenry(double value)
        {
            return value * 9.9999999999999995e-07d;
        }

        public static double HenryToMicrohenry(double baseValue)
        {
            return baseValue / 9.9999999999999995e-07d;
        }

        public static double MillihenryToHenry(double value)
        {
            return value * 0.001d;
        }

        public static double HenryToMillihenry(double baseValue)
        {
            return baseValue / 0.001d;
        }

        public static double HenryToHenry(double value)
        {
            return value;
        }

        public static double KilohenryToHenry(double value)
        {
            return value * 1000.0d;
        }

        public static double HenryToKilohenry(double baseValue)
        {
            return baseValue / 1000.0d;
        }

        public static double FemtohenryToHenry(double value)
        {
            return value * 1.0000000000000001e-15d;
        }

        public static double HenryToFemtohenry(double baseValue)
        {
            return baseValue / 1.0000000000000001e-15d;
        }

        public static double PicohenryToHenry(double value)
        {
            return value * 9.9999999999999998e-13d;
        }

        public static double HenryToPicohenry(double baseValue)
        {
            return baseValue / 9.9999999999999998e-13d;
        }

        public static double MegahenryToHenry(double value)
        {
            return value * 1000000.0d;
        }

        public static double HenryToMegahenry(double baseValue)
        {
            return baseValue / 1000000.0d;
        }

        public static double GigahenryToHenry(double value)
        {
            return value * 1000000000.0d;
        }

        public static double HenryToGigahenry(double baseValue)
        {
            return baseValue / 1000000000.0d;
        }

        public static double CentihenryToHenry(double value)
        {
            return value * 0.01d;
        }

        public static double HenryToCentihenry(double baseValue)
        {
            return baseValue / 0.01d;
        }

        public static double DecihenryToHenry(double value)
        {
            return value * 0.10000000000000001d;
        }

        public static double HenryToDecihenry(double baseValue)
        {
            return baseValue / 0.10000000000000001d;
        }

        public static double DecahenryToHenry(double value)
        {
            return value * 10.0d;
        }

        public static double HenryToDecahenry(double baseValue)
        {
            return baseValue / 10.0d;
        }

        public static double HectohenryToHenry(double value)
        {
            return value * 100.0d;
        }

        public static double HenryToHectohenry(double baseValue)
        {
            return baseValue / 100.0d;
        }
    }
}

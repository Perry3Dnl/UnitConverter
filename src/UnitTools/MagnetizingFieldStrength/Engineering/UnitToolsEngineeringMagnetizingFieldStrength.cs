namespace UnitTools.MagnetizingFieldStrength.Engineering
{
    public static class UnitToolsEngineeringMagnetizingFieldStrength
    {
        public static double AmpereTurnPerMeterToAmperePerMeter(double value)
        {
            return value * 1.0d;
        }

        public static double AmperePerMeterToAmpereTurnPerMeter(double baseValue)
        {
            return baseValue / 1.0d;
        }
    }
}

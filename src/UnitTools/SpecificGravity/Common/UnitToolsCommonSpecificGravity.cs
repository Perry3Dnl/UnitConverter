namespace UnitTools.SpecificGravity.Common
{
    public static class UnitToolsCommonSpecificGravity
    {
        public static double RatioToRatio(double value)
        {
            return value;
        }

        public static double SpecificGravityToRatio(double value)
        {
            return value;
        }

        public static double RatioToSpecificGravity(double baseValue)
        {
            return baseValue;
        }


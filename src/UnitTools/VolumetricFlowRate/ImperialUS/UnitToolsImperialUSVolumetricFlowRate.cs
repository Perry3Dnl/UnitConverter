namespace UnitTools.VolumetricFlowRate.ImperialUS
{
    public static class UnitToolsImperialUSVolumetricFlowRate
    {
        public static double USGallonPerMinuteToCubicMeterPerSecond(double value)
        {
            return value * 6.3090196400000003e-05d;
        }

        public static double CubicMeterPerSecondToUSGallonPerMinute(double baseValue)
        {
            return baseValue / 6.3090196400000003e-05d;
        }

        public static double USGallonPerHourToCubicMeterPerSecond(double value)
        {
            return value * 1.0515032733333334e-06d;
        }

        public static double CubicMeterPerSecondToUSGallonPerHour(double baseValue)
        {
            return baseValue / 1.0515032733333334e-06d;
        }

        public static double USGallonPerSecondToCubicMeterPerSecond(double value)
        {
            return value * 0.0037854117840000001d;
        }

        public static double CubicMeterPerSecondToUSGallonPerSecond(double baseValue)
        {
            return baseValue / 0.0037854117840000001d;
        }

        public static double USGallonPerDayToCubicMeterPerSecond(double value)
        {
            return value * 4.3812636388888893e-08d;
        }

        public static double CubicMeterPerSecondToUSGallonPerDay(double baseValue)
        {
            return baseValue / 4.3812636388888893e-08d;
        }

        public static double OilBarrelPerDayToCubicMeterPerSecond(double value)
        {
            return value * 1.8401307283333336e-06d;
        }

        public static double CubicMeterPerSecondToOilBarrelPerDay(double baseValue)
        {
            return baseValue / 1.8401307283333336e-06d;
        }

        public static double OilBarrelPerHourToCubicMeterPerSecond(double value)
        {
            return value * 4.4163137480000004e-05d;
        }

        public static double CubicMeterPerSecondToOilBarrelPerHour(double baseValue)
        {
            return baseValue / 4.4163137480000004e-05d;
        }

        public static double MillionUSGallonsPerDayToCubicMeterPerSecond(double value)
        {
            return value * 0.043812636388888888d;
        }

        public static double CubicMeterPerSecondToMillionUSGallonsPerDay(double baseValue)
        {
            return baseValue / 0.043812636388888888d;
        }

        public static double USFluidOuncePerSecondToCubicMeterPerSecond(double value)
        {
            return value * 2.9573529562500001e-05d;
        }

        public static double CubicMeterPerSecondToUSFluidOuncePerSecond(double baseValue)
        {
            return baseValue / 2.9573529562500001e-05d;
        }
    }
}

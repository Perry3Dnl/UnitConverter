namespace RealisticPhysics.UnitConversion.SurfaceTension.Imperial
{
    public static class UnitConverterImperialSurfaceTension
    {
        public static double PoundForcePerFootToNewtonPerMeter(double value)
        {
            return value * 14.593902937206362d;
        }

        public static double NewtonPerMeterToPoundForcePerFoot(double baseValue)
        {
            return baseValue / 14.593902937206362d;
        }

        public static double PoundForcePerInchToNewtonPerMeter(double value)
        {
            return value * 175.12683524647636d;
        }

        public static double NewtonPerMeterToPoundForcePerInch(double baseValue)
        {
            return baseValue / 175.12683524647636d;
        }

        public static double PoundalPerFootToNewtonPerMeter(double value)
        {
            return value * 0.45359236999999997d;
        }

        public static double NewtonPerMeterToPoundalPerFoot(double baseValue)
        {
            return baseValue / 0.45359236999999997d;
        }

        public static double OunceForcePerFootToNewtonPerMeter(double value)
        {
            return value * 0.91211893357539764d;
        }

        public static double NewtonPerMeterToOunceForcePerFoot(double baseValue)
        {
            return baseValue / 0.91211893357539764d;
        }
    }
}

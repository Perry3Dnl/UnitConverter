namespace RealisticPhysics.UnitConversion.DataRate.Digital
{
    public static class UnitConverterDigitalDataRate
    {
        public static double BitPerSecondToBitPerSecond(double value)
        {
            return value;
        }

        public static double BytePerSecondToBitPerSecond(double value)
        {
            return value * 8.0d;
        }

        public static double BitPerSecondToBytePerSecond(double baseValue)
        {
            return baseValue / 8.0d;
        }

        public static double KilobitPerSecondToBitPerSecond(double value)
        {
            return value * 1000.0d;
        }

        public static double BitPerSecondToKilobitPerSecond(double baseValue)
        {
            return baseValue / 1000.0d;
        }

        public static double KilobytePerSecondToBitPerSecond(double value)
        {
            return value * 8000.0d;
        }

        public static double BitPerSecondToKilobytePerSecond(double baseValue)
        {
            return baseValue / 8000.0d;
        }

        public static double MegabitPerSecondToBitPerSecond(double value)
        {
            return value * 1000000.0d;
        }

        public static double BitPerSecondToMegabitPerSecond(double baseValue)
        {
            return baseValue / 1000000.0d;
        }

        public static double MegabytePerSecondToBitPerSecond(double value)
        {
            return value * 8000000.0d;
        }

        public static double BitPerSecondToMegabytePerSecond(double baseValue)
        {
            return baseValue / 8000000.0d;
        }

        public static double GigabitPerSecondToBitPerSecond(double value)
        {
            return value * 1000000000.0d;
        }

        public static double BitPerSecondToGigabitPerSecond(double baseValue)
        {
            return baseValue / 1000000000.0d;
        }

        public static double GigabytePerSecondToBitPerSecond(double value)
        {
            return value * 8000000000.0d;
        }

        public static double BitPerSecondToGigabytePerSecond(double baseValue)
        {
            return baseValue / 8000000000.0d;
        }

        public static double KibibitPerSecondToBitPerSecond(double value)
        {
            return value * 1024.0d;
        }

        public static double BitPerSecondToKibibitPerSecond(double baseValue)
        {
            return baseValue / 1024.0d;
        }

        public static double KibibytePerSecondToBitPerSecond(double value)
        {
            return value * 8192.0d;
        }

        public static double BitPerSecondToKibibytePerSecond(double baseValue)
        {
            return baseValue / 8192.0d;
        }

        public static double MebibitPerSecondToBitPerSecond(double value)
        {
            return value * 1048576.0d;
        }

        public static double BitPerSecondToMebibitPerSecond(double baseValue)
        {
            return baseValue / 1048576.0d;
        }

        public static double MebibytePerSecondToBitPerSecond(double value)
        {
            return value * 8388608.0d;
        }

        public static double BitPerSecondToMebibytePerSecond(double baseValue)
        {
            return baseValue / 8388608.0d;
        }

        public static double GibibitPerSecondToBitPerSecond(double value)
        {
            return value * 1073741824.0d;
        }

        public static double BitPerSecondToGibibitPerSecond(double baseValue)
        {
            return baseValue / 1073741824.0d;
        }

        public static double GibibytePerSecondToBitPerSecond(double value)
        {
            return value * 8589934592.0d;
        }

        public static double BitPerSecondToGibibytePerSecond(double baseValue)
        {
            return baseValue / 8589934592.0d;
        }
    }
}

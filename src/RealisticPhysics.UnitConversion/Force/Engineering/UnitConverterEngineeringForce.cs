namespace RealisticPhysics.UnitConversion.Force.Engineering
{
    public static class UnitConverterEngineeringForce
    {
        public static double JoulePerMeterToNewton(double value)
        {
            return value * 1.0d;
        }

        public static double NewtonToJoulePerMeter(double baseValue)
        {
            return baseValue / 1.0d;
        }
    }
}

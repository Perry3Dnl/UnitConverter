namespace RealisticPhysics.UnitConversion.DynamicViscosity.Metric
{
    public static class UnitConverterMetricDynamicViscosity
    {
        public static double PascalSecondToPascalSecond(double value)
        {
            return value;
        }

        public static double MillipascalSecondToPascalSecond(double value)
        {
            return value * 0.001d;
        }

        public static double PascalSecondToMillipascalSecond(double baseValue)
        {
            return baseValue / 0.001d;
        }

        public static double MicropascalSecondToPascalSecond(double value)
        {
            return value * 9.9999999999999995e-07d;
        }

        public static double PascalSecondToMicropascalSecond(double baseValue)
        {
            return baseValue / 9.9999999999999995e-07d;
        }

        public static double PoiseToPascalSecond(double value)
        {
            return value * 0.10000000000000001d;
        }

        public static double PascalSecondToPoise(double baseValue)
        {
            return baseValue / 0.10000000000000001d;
        }

        public static double CentipoiseToPascalSecond(double value)
        {
            return value * 0.001d;
        }

        public static double PascalSecondToCentipoise(double baseValue)
        {
            return baseValue / 0.001d;
        }

        public static double KilopascalSecondToPascalSecond(double value)
        {
            return value * 1000.0d;
        }

        public static double PascalSecondToKilopascalSecond(double baseValue)
        {
            return baseValue / 1000.0d;
        }

        public static double MegapascalSecondToPascalSecond(double value)
        {
            return value * 1000000.0d;
        }

        public static double PascalSecondToMegapascalSecond(double baseValue)
        {
            return baseValue / 1000000.0d;
        }

        public static double KilogramPerMeterSecondToPascalSecond(double value)
        {
            return value * 1.0d;
        }

        public static double PascalSecondToKilogramPerMeterSecond(double baseValue)
        {
            return baseValue / 1.0d;
        }

        public static double GramPerCentimeterSecondToPascalSecond(double value)
        {
            return value * 0.10000000000000001d;
        }

        public static double PascalSecondToGramPerCentimeterSecond(double baseValue)
        {
            return baseValue / 0.10000000000000001d;
        }

        public static double MillipoiseToPascalSecond(double value)
        {
            return value * 0.0001d;
        }

        public static double PascalSecondToMillipoise(double baseValue)
        {
            return baseValue / 0.0001d;
        }

        public static double MicropoiseToPascalSecond(double value)
        {
            return value * 9.9999999999999995e-08d;
        }

        public static double PascalSecondToMicropoise(double baseValue)
        {
            return baseValue / 9.9999999999999995e-08d;
        }

        public static double PascalHourToPascalSecond(double value)
        {
            return value * 3600.0d;
        }

        public static double PascalSecondToPascalHour(double baseValue)
        {
            return baseValue / 3600.0d;
        }

        public static double PascalMinuteToPascalSecond(double value)
        {
            return value * 60.0d;
        }

        public static double PascalSecondToPascalMinute(double baseValue)
        {
            return baseValue / 60.0d;
        }

        public static double KilogramPerMeterHourToPascalSecond(double value)
        {
            return value * 0.00027777777777777778d;
        }

        public static double PascalSecondToKilogramPerMeterHour(double baseValue)
        {
            return baseValue / 0.00027777777777777778d;
        }

        public static double GramPerCentimeterMinuteToPascalSecond(double value)
        {
            return value * 0.0016666666666666668d;
        }

        public static double PascalSecondToGramPerCentimeterMinute(double baseValue)
        {
            return baseValue / 0.0016666666666666668d;
        }
    }

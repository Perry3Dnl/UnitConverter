namespace RealisticPhysics.UnitConversion.RadiationDose.Metric
{
    public static class UnitConverterMetricRadiationDose
    {
        public static double NanograyToGray(double value)
        {
            return value * 1.0000000000000001e-09d;
        }

        public static double GrayToNanogray(double baseValue)
        {
            return baseValue / 1.0000000000000001e-09d;
        }

        public static double MicrograyToGray(double value)
        {
            return value * 9.9999999999999995e-07d;
        }

        public static double GrayToMicrogray(double baseValue)
        {
            return baseValue / 9.9999999999999995e-07d;
        }

        public static double MilligrayToGray(double value)
        {
            return value * 0.001d;
        }

        public static double GrayToMilligray(double baseValue)
        {
            return baseValue / 0.001d;
        }

        public static double GrayToGray(double value)
        {
            return value;
        }

        public static double PicograyToGray(double value)
        {
            return value * 9.9999999999999998e-13d;
        }

        public static double GrayToPicogray(double baseValue)
        {
            return baseValue / 9.9999999999999998e-13d;
        }

        public static double CentigrayToGray(double value)
        {
            return value * 0.01d;
        }

        public static double GrayToCentigray(double baseValue)
        {
            return baseValue / 0.01d;
        }

        public static double KilograyToGray(double value)
        {
            return value * 1000.0d;
        }

        public static double GrayToKilogray(double baseValue)
        {
            return baseValue / 1000.0d;
        }

        public static double MegagrayToGray(double value)
        {
            return value * 1000000.0d;
        }

        public static double GrayToMegagray(double baseValue)
        {
            return baseValue / 1000000.0d;
        }

        public static double DecigrayToGray(double value)
        {
            return value * 0.10000000000000001d;
        }

        public static double GrayToDecigray(double baseValue)
        {
            return baseValue / 0.10000000000000001d;
        }

        public static double DekagrayToGray(double value)
        {
            return value * 10.0d;
        }

        public static double GrayToDekagray(double baseValue)
        {
            return baseValue / 10.0d;
        }

        public static double HectograyToGray(double value)
        {
            return value * 100.0d;
        }

        public static double GrayToHectogray(double baseValue)
        {
            return baseValue / 100.0d;
        }

        public static double NanosievertToGray(double value)
        {
            return value * 1.0000000000000001e-09d;
        }

        public static double GrayToNanosievert(double baseValue)
        {
            return baseValue / 1.0000000000000001e-09d;
        }
    }
}

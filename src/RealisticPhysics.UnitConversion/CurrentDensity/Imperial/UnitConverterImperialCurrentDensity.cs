namespace RealisticPhysics.UnitConversion.CurrentDensity.Imperial
{
    public static class UnitConverterImperialCurrentDensity
    {
        public static double AmperePerSquareInchToAmperePerSquareMeter(double value)
        {
            return value * 1550.0031000062002d;
        }

        public static double AmperePerSquareMeterToAmperePerSquareInch(double baseValue)
        {
            return baseValue / 1550.0031000062002d;
        }

        public static double AmperePerSquareFootToAmperePerSquareMeter(double value)
        {
            return value * 10.763910416709722d;
        }

        public static double AmperePerSquareMeterToAmperePerSquareFoot(double baseValue)
        {
            return baseValue / 10.763910416709722d;
        }

        public static double MilliamperePerSquareInchToAmperePerSquareMeter(double value)
        {
            return value * 1.5500031000062d;
        }

        public static double AmperePerSquareMeterToMilliamperePerSquareInch(double baseValue)
        {
            return baseValue / 1.5500031000062d;
        }
    }
}

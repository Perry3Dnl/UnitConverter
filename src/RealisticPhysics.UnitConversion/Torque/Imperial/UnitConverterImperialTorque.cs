namespace RealisticPhysics.UnitConversion.Torque.Imperial
{
    public static class UnitConverterImperialTorque
    {
        public static double PoundForceFootToNewtonMeter(double value)
        {
            return value * 1.3558179483314003d;
        }

        public static double NewtonMeterToPoundForceFoot(double baseValue)
        {
            return baseValue / 1.3558179483314003d;
        }

        public static double PoundForceInchToNewtonMeter(double value)
        {
            return value * 0.1129848290276167d;
        }

        public static double NewtonMeterToPoundForceInch(double baseValue)
        {
            return baseValue / 0.1129848290276167d;
        }

        public static double OunceForceInchToNewtonMeter(double value)
        {
            return value * 0.0070615518142260001d;
        }

        public static double NewtonMeterToOunceForceInch(double baseValue)
        {
            return baseValue / 0.0070615518142260001d;
        }

        public static double PoundForceYardToNewtonMeter(double value)
        {
            return value * 4.0674538449942013d;
        }

        public static double NewtonMeterToPoundForceYard(double baseValue)
        {
            return baseValue / 4.0674538449942013d;
        }

        public static double OunceForceFootToNewtonMeter(double value)
        {
            return value * 0.084738621770712522d;
        }

        public static double NewtonMeterToOunceForceFoot(double baseValue)
        {
            return baseValue / 0.084738621770712522d;
        }

        public static double PoundalFootToNewtonMeter(double value)
        {
            return value * 0.042140110093804799d;
        }

        public static double NewtonMeterToPoundalFoot(double baseValue)
        {
            return baseValue / 0.042140110093804799d;
        }
    }
}

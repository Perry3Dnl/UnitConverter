namespace RealisticPhysics.UnitConversion.LuminousFlux.Historical
{
    public static class UnitConverterHistoricalLuminousFlux
    {
        public static double TalbotPerSecondToLumen(double value)
        {
            return value * 1.0d;
        }

        public static double LumenToTalbotPerSecond(double baseValue)
        {
            return baseValue / 1.0d;
        }
    }
}

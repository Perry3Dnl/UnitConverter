namespace RealisticPhysics.UnitConversion.Area.Survey
{
    public static class UnitConverterSurveyArea
    {
        public static double SquareRodToSquareMeter(double value)
        {
            return value * 25.29285264d;
        }

        public static double SquareMeterToSquareRod(double baseValue)
        {
            return baseValue / 25.29285264d;
        }

        public static double SquarePoleToSquareMeter(double value)
        {
            return value * 25.29285264d;
        }

        public static double SquareMeterToSquarePole(double baseValue)
        {
            return baseValue / 25.29285264d;
        }

        public static double SquarePerchToSquareMeter(double value)
        {
            return value * 25.29285264d;
        }

        public static double SquareMeterToSquarePerch(double baseValue)
        {
            return baseValue / 25.29285264d;
        }

        public static double SquareChainToSquareMeter(double value)
        {
            return value * 404.68564223999999d;

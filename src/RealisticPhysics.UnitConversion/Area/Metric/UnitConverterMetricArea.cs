namespace RealisticPhysics.UnitConversion.Area.Metric
{
    public static class UnitConverterMetricArea
    {
        public static double SquareMillimeterToSquareMeter(double value)
        {
            return value * 9.9999999999999995e-07d;
        }

        public static double SquareMeterToSquareMillimeter(double baseValue)
        {
            return baseValue / 9.9999999999999995e-07d;
        }

        public static double SquareCentimeterToSquareMeter(double value)
        {
            return value * 0.0001d;
        }

        public static double SquareMeterToSquareCentimeter(double baseValue)
        {
            return baseValue / 0.0001d;
        }

        public static double SquareMeterToSquareMeter(double value)
        {
            return value;
        }

        public static double AreToSquareMeter(double value)
        {
            return value * 100.0d;
        }

        public static double SquareMeterToAre(double baseValue)
        {
            return baseValue / 100.0d;
        }

        public static double HectareToSquareMeter(double value)
        {
            return value * 10000.0d;
        }

        public static double SquareMeterToHectare(double baseValue)
        {
            return baseValue / 10000.0d;
        }

        public static double SquareKilometerToSquareMeter(double value)
        {
            return value * 1000000.0d;
        }

        public static double SquareMeterToSquareKilometer(double baseValue)
        {
            return baseValue / 1000000.0d;
        }

        public static double SquareNanometerToSquareMeter(double value)
        {
            return value * 1.0000000000000001e-18d;
        }

        public static double SquareMeterToSquareNanometer(double baseValue)
        {
            return baseValue / 1.0000000000000001e-18d;
        }

        public static double SquareMicrometerToSquareMeter(double value)
        {
            return value * 9.9999999999999998e-13d;
        }

        public static double SquareMeterToSquareMicrometer(double baseValue)
        {
            return baseValue / 9.9999999999999998e-13d;
        }

        public static double SquareDecimeterToSquareMeter(double value)
        {
            return value * 0.01d;
        }

        public static double SquareMeterToSquareDecimeter(double baseValue)
        {
            return baseValue / 0.01d;
        }

        public static double SquareDecameterToSquareMeter(double value)
        {
            return value * 100.0d;
        }

        public static double SquareMeterToSquareDecameter(double baseValue)
        {
            return baseValue / 100.0d;
        }

        public static double SquareHectometerToSquareMeter(double value)
        {
            return value * 10000.0d;
        }

        public static double SquareMeterToSquareHectometer(double baseValue)
        {
            return baseValue / 10000.0d;
        }

        public static double SquareMegameterToSquareMeter(double value)
        {
            return value * 1000000000000.0d;
        }

        public static double SquareMeterToSquareMegameter(double baseValue)
        {
            return baseValue / 1000000000000.0d;
        }
    }
}

namespace RealisticPhysics.UnitConversion.VolumetricFlowRate.Imperial
{
    public static class UnitConverterImperialVolumetricFlowRate
    {
        public static double CubicFootPerSecondToCubicMeterPerSecond(double value)
        {
            return value * 0.028316846592000001d;
        }

        public static double CubicMeterPerSecondToCubicFootPerSecond(double baseValue)
        {
            return baseValue / 0.028316846592000001d;
        }

        public static double CubicFootPerMinuteToCubicMeterPerSecond(double value)
        {
            return value * 0.00047194744319999999d;
        }

        public static double CubicMeterPerSecondToCubicFootPerMinute(double baseValue)
        {
            return baseValue / 0.00047194744319999999d;
        }

        public static double CubicFootPerHourToCubicMeterPerSecond(double value)
        {
            return value * 7.8657907200000004e-06d;
        }

        public static double CubicMeterPerSecondToCubicFootPerHour(double baseValue)
        {
            return baseValue / 7.8657907200000004e-06d;
        }

        public static double CubicInchPerSecondToCubicMeterPerSecond(double value)
        {
            return value * 1.6387063999999999e-05d;
        }

        public static double CubicMeterPerSecondToCubicInchPerSecond(double baseValue)
        {
            return baseValue / 1.6387063999999999e-05d;
        }

        public static double CubicInchPerMinuteToCubicMeterPerSecond(double value)
        {
            return value * 2.7311773333333333e-07d;
        }

        public static double CubicMeterPerSecondToCubicInchPerMinute(double baseValue)
        {
            return baseValue / 2.7311773333333333e-07d;
        }

        public static double CubicYardPerSecondToCubicMeterPerSecond(double value)
        {
            return value * 0.76455485798400002d;
        }

        public static double CubicMeterPerSecondToCubicYardPerSecond(double baseValue)
        {
            return baseValue / 0.76455485798400002d;
        }

        public static double CubicYardPerMinuteToCubicMeterPerSecond(double value)
        {
            return value * 0.0127425809664d;
        }

        public static double CubicMeterPerSecondToCubicYardPerMinute(double baseValue)
        {
            return baseValue / 0.0127425809664d;
        }

        public static double CubicYardPerHourToCubicMeterPerSecond(double value)
        {
            return value * 0.00021237634944000001d;
        }

        public static double CubicMeterPerSecondToCubicYardPerHour(double baseValue)
        {
            return baseValue / 0.00021237634944000001d;
        }
    }
}

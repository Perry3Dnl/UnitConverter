namespace RealisticPhysics.UnitConversion.Length.Common
{
    public static class UnitConverterCommonLength
    {
        public static double PointPostScriptToMeter(double value)
        {
            return value * 0.00035277777777777776d;
        }

        public static double MeterToPointPostScript(double baseValue)
        {
            return baseValue / 0.00035277777777777776d;
        }

        public static double PicaPostScriptToMeter(double value)
        {
            return value * 0.0042333333333333329d;
        }

        public static double MeterToPicaPostScript(double baseValue)
        {
            return baseValue / 0.0042333333333333329d;
        }

        public static double TwipToMeter(double value)
        {
            return value * 1.7638888888888889e-05d;
        }

        public static double MeterToTwip(double baseValue)
        {
            return baseValue / 1.7638888888888889e-05d;
        }

        public static double PrinterPointToMeter(double value)
        {
            return value * 0.00035145980351459799d;
        }

        public static double MeterToPrinterPoint(double baseValue)
        {
            return baseValue / 0.00035145980351459799d;
        }

        public static double PrinterPicaToMeter(double value)
        {
            return value * 0.0042175176421751764d;
        }

        public static double MeterToPrinterPica(double baseValue)
        {
            return baseValue / 0.0042175176421751764d;
        }

        public static double RackUnitToMeter(double value)
        {
            return value * 0.044450000000000003d;
        }

        public static double MeterToRackUnit(double baseValue)
        {
            return baseValue / 0.044450000000000003d;
        }
    }
}

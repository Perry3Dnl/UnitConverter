namespace RealisticPhysics.UnitConversion.Length.Astronomical
{
    public static class UnitConverterAstronomicalLength
    {
        public static double AstronomicalUnitToMeter(double value)
        {
            return value * 149597870700.0d;
        }

        public static double MeterToAstronomicalUnit(double baseValue)
        {
            return baseValue / 149597870700.0d;
        }

        public static double LightYearToMeter(double value)
        {
            return value * 9460730472580800.0d;
        }

        public static double MeterToLightYear(double baseValue)
        {
            return baseValue / 9460730472580800.0d;
        }

        public static double ParsecToMeter(double value)
        {
            return value * 30856775814913672.0d;
        }

        public static double MeterToParsec(double baseValue)
        {
            return baseValue / 30856775814913672.0d;
        }

        public static double EarthEquatorialRadiusToMeter(double value)
        {
            return value * 6378137.0d;
        }

        public static double MeterToEarthEquatorialRadius(double baseValue)
        {
            return baseValue / 6378137.0d;
        }

        public static double EarthMeanRadiusToMeter(double value)
        {
            return value * 6371008.7999999998d;
        }

        public static double MeterToEarthMeanRadius(double baseValue)
        {
            return baseValue / 6371008.7999999998d;
        }

        public static double SolarRadiusToMeter(double value)
        {
            return value * 695700000.0d;
        }

        public static double MeterToSolarRadius(double baseValue)
        {
            return baseValue / 695700000.0d;
        }

        public static double LunarDistanceToMeter(double value)
        {
            return value * 384400000.0d;
        }

        public static double MeterToLunarDistance(double baseValue)
        {
            return baseValue / 384400000.0d;
        }

        public static double KiloparsecToMeter(double value)
        {
            return value * 3.0856775814913671e+19d;
        }

        public static double MeterToKiloparsec(double baseValue)
        {
            return baseValue / 3.0856775814913671e+19d;
        }

        public static double MegaparsecToMeter(double value)
        {
            return value * 3.0856775814913672e+22d;
        }

        public static double MeterToMegaparsec(double baseValue)
        {
            return baseValue / 3.0856775814913672e+22d;
        }

        public static double GigaparsecToMeter(double value)
        {
            return value * 3.0856775814913673e+25d;
        }

        public static double MeterToGigaparsec(double baseValue)
        {
            return baseValue / 3.0856775814913673e+25d;
        }

        public static double LightSecondToMeter(double value)
        {
            return value * 299792458.0d;
        }

        public static double MeterToLightSecond(double baseValue)
        {
            return baseValue / 299792458.0d;
        }

        public static double LightMinuteToMeter(double value)
        {
            return value * 17987547480.0d;
        }

        public static double MeterToLightMinute(double baseValue)
        {
            return baseValue / 17987547480.0d;
        }

        public static double LightHourToMeter(double value)
        {
            return value * 1079252848800.0d;
        }

        public static double MeterToLightHour(double baseValue)
        {
            return baseValue / 1079252848800.0d;
        }

        public static double LightDayToMeter(double value)
        {
            return value * 25902068371200.0d;
        }

        public static double MeterToLightDay(double baseValue)
        {
            return baseValue / 25902068371200.0d;
        }

        public static double LightWeekToMeter(double value)
        {
            return value * 181314478598400.0d;
        }

        public static double MeterToLightWeek(double baseValue)
        {
            return baseValue / 181314478598400.0d;
        }
    }
}

namespace RealisticPhysics.UnitConversion.Conductance.Metric
{
    public static class UnitConverterMetricConductance
    {
        public static double NanosiemensToSiemens(double value)
        {
            return value * 1.0000000000000001e-09d;
        }

        public static double SiemensToNanosiemens(double baseValue)
        {
            return baseValue / 1.0000000000000001e-09d;
        }

        public static double MicrosiemensToSiemens(double value)
        {
            return value * 9.9999999999999995e-07d;
        }

        public static double SiemensToMicrosiemens(double baseValue)
        {
            return baseValue / 9.9999999999999995e-07d;
        }

        public static double MillisiemensToSiemens(double value)
        {
            return value * 0.001d;
        }

        public static double SiemensToMillisiemens(double baseValue)
        {
            return baseValue / 0.001d;
        }

        public static double SiemensToSiemens(double value)
        {
            return value;
        }

        public static double KilosiemensToSiemens(double value)
        {
            return value * 1000.0d;
        }

        public static double SiemensToKilosiemens(double baseValue)
        {
            return baseValue / 1000.0d;
        }

        public static double FemtosiemensToSiemens(double value)
        {
            return value * 1.0000000000000001e-15d;
        }

        public static double SiemensToFemtosiemens(double baseValue)
        {
            return baseValue / 1.0000000000000001e-15d;
        }

        public static double PicosiemensToSiemens(double value)
        {
            return value * 9.9999999999999998e-13d;
        }

        public static double SiemensToPicosiemens(double baseValue)
        {
            return baseValue / 9.9999999999999998e-13d;
        }

        public static double MegasiemensToSiemens(double value)
        {
            return value * 1000000.0d;
        }

        public static double SiemensToMegasiemens(double baseValue)
        {
            return baseValue / 1000000.0d;
        }

        public static double GigasiemensToSiemens(double value)
        {
            return value * 1000000000.0d;
        }

        public static double SiemensToGigasiemens(double baseValue)
        {
            return baseValue / 1000000000.0d;
        }

        public static double CentisiemensToSiemens(double value)
        {
            return value * 0.01d;
        }

        public static double SiemensToCentisiemens(double baseValue)
        {
            return baseValue / 0.01d;
        }

        public static double DecisiemensToSiemens(double value)
        {
            return value * 0.10000000000000001d;
        }

        public static double SiemensToDecisiemens(double baseValue)
        {
            return baseValue / 0.10000000000000001d;
        }

        public static double DecasiemensToSiemens(double value)
        {
            return value * 10.0d;
        }

        public static double SiemensToDecasiemens(double baseValue)
        {
            return baseValue / 10.0d;
        }

        public static double HectosiemensToSiemens(double value)
        {
            return value * 100.0d;
        }

        public static double SiemensToHectosiemens(double baseValue)
        {
            return baseValue / 100.0d;
        }
    }
}

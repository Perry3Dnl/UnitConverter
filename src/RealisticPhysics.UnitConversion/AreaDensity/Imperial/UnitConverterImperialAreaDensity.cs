namespace RealisticPhysics.UnitConversion.AreaDensity.Imperial
{
    public static class UnitConverterImperialAreaDensity
    {
        public static double PoundPerSquareFootToKilogramPerSquareMeter(double value)
        {
            return value * 4.8824276363830501d;
        }

        public static double KilogramPerSquareMeterToPoundPerSquareFoot(double baseValue)
        {
            return baseValue / 4.8824276363830501d;
        }

        public static double PoundPerSquareInchToKilogramPerSquareMeter(double value)
        {
            return value * 703.06957963915931d;
        }

        public static double KilogramPerSquareMeterToPoundPerSquareInch(double baseValue)
        {
            return baseValue / 703.06957963915931d;
        }

        public static double OuncePerSquareYardToKilogramPerSquareMeter(double value)
        {
            return value * 0.0339057474748823d;
        }

        public static double KilogramPerSquareMeterToOuncePerSquareYard(double baseValue)
        {
            return baseValue / 0.0339057474748823d;
        }

        public static double OuncePerSquareFootToKilogramPerSquareMeter(double value)
        {
            return value * 0.30515172727394063d;
        }

        public static double KilogramPerSquareMeterToOuncePerSquareFoot(double baseValue)
        {
            return baseValue / 0.30515172727394063d;
        }

        public static double OuncePerSquareInchToKilogramPerSquareMeter(double value)
        {
            return value * 43.941848727447457d;
        }

        public static double KilogramPerSquareMeterToOuncePerSquareInch(double baseValue)
        {
            return baseValue / 43.941848727447457d;
        }

        public static double PoundPerSquareYardToKilogramPerSquareMeter(double value)
        {
            return value * 0.5424919595981168d;
        }

        public static double KilogramPerSquareMeterToPoundPerSquareYard(double baseValue)
        {
            return baseValue / 0.5424919595981168d;
        }
    }
}

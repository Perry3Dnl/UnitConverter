namespace RealisticPhysics.UnitConversion.Mass.Apothecaries
{
    public static class UnitConverterApothecariesMass
    {
        public static double ApothecariesScrupleToKilogram(double value)
        {
            return value * 0.0012959782d;
        }

        public static double KilogramToApothecariesScruple(double baseValue)
        {
            return baseValue / 0.0012959782d;
        }

        public static double ApothecariesDramToKilogram(double value)
        {
            return value * 0.0038879346000000002d;
        }

        public static double KilogramToApothecariesDram(double baseValue)
        {
            return baseValue / 0.0038879346000000002d;
        }

        public static double ApothecariesOunceToKilogram(double value)
        {
            return value * 0.031103476800000002d;
        }

        public static double KilogramToApothecariesOunce(double baseValue)
        {
            return baseValue / 0.031103476800000002d;
        }

        public static double ApothecariesPoundToKilogram(double value)
        {
            return value * 0.37324172160000002d;
        }

        public static double KilogramToApothecariesPound(double baseValue)
        {
            return baseValue / 0.37324172160000002d;
        }
    }
}

namespace UnitConverter.Angle.Metric
{
    public static class UnitConverterMetricAngle
    {
        public static double GradianToDegree(double value)
        {
            return value * 0.90000000000000002d;
        }

        public static double DegreeToGradian(double baseValue)
        {
            return baseValue / 0.90000000000000002d;
        }

        public static double MicroradianToDegree(double value)
        {
            return value * 5.7295779513082317e-05d;
        }

        public static double DegreeToMicroradian(double baseValue)
        {
            return baseValue / 5.7295779513082317e-05d;
        }

        public static double NanoradianToDegree(double value)
        {
            return value * 5.7295779513082331e-08d;
        }

        public static double DegreeToNanoradian(double baseValue)
        {
            return baseValue / 5.7295779513082331e-08d;
        }

        public static double MilliarcsecondToDegree(double value)
        {
            return value * 2.7777777777777776e-07d;
        }

        public static double DegreeToMilliarcsecond(double baseValue)
        {
            return baseValue / 2.7777777777777776e-07d;
        }

        public static double MicroarcsecondToDegree(double value)
        {
            return value * 2.7777777777777777e-10d;
        }

        public static double DegreeToMicroarcsecond(double baseValue)
        {
            return baseValue / 2.7777777777777777e-10d;
        }

        public static double NatoMilToDegree(double value)
        {
            return value * 0.056250000000000001d;
        }

        public static double DegreeToNatoMil(double baseValue)
        {
            return baseValue / 0.056250000000000001d;
        }

        public static double ArtilleryMilToDegree(double value)
        {
            return value * 0.059999999999999998d;
        }

        public static double DegreeToArtilleryMil(double baseValue)
        {
            return baseValue / 0.059999999999999998d;
        }

        public static double BinaryDegreeToDegree(double value)
        {
            return value * 1.40625d;
        }

        public static double DegreeToBinaryDegree(double baseValue)
        {
            return baseValue / 1.40625d;
        }
    }
}

namespace UnitConverter.SpecificWeight.ImperialUK
{
    public static class UnitConverterImperialUKSpecificWeight
    {
        public static double PoundForcePerImperialGallonToNewtonPerCubicMeter(double value)
        {
            return value * 978.47196497660616d;
        }

        public static double NewtonPerCubicMeterToPoundForcePerImperialGallon(double baseValue)
        {
            return baseValue / 978.47196497660616d;
        }
    }
}

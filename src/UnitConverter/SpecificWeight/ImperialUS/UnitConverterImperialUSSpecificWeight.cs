namespace UnitConverter.SpecificWeight.ImperialUS
{
    public static class UnitConverterImperialUSSpecificWeight
    {
        public static double PoundForcePerUSGallonToNewtonPerCubicMeter(double value)
        {
            return value * 1175.0958334472441d;
        }

        public static double NewtonPerCubicMeterToPoundForcePerUSGallon(double baseValue)
        {
            return baseValue / 1175.0958334472441d;
        }
    }
}

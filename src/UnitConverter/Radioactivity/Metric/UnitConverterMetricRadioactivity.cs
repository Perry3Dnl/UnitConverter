namespace UnitConverter.Radioactivity.Metric
{
    public static class UnitConverterMetricRadioactivity
    {
        public static double BecquerelToBecquerel(double value)
        {
            return value;
        }

        public static double KilobecquerelToBecquerel(double value)
        {
            return value * 1000.0d;
        }

        public static double BecquerelToKilobecquerel(double baseValue)
        {
            return baseValue / 1000.0d;
        }

        public static double MegabecquerelToBecquerel(double value)
        {
            return value * 1000000.0d;
        }

        public static double BecquerelToMegabecquerel(double baseValue)
        {
            return baseValue / 1000000.0d;
        }

        public static double GigabecquerelToBecquerel(double value)
        {
            return value * 1000000000.0d;
        }

        public static double BecquerelToGigabecquerel(double baseValue)
        {
            return baseValue / 1000000000.0d;
        }

        public static double TerabecquerelToBecquerel(double value)
        {
            return value * 1000000000000.0d;
        }

        public static double BecquerelToTerabecquerel(double baseValue)
        {
            return baseValue / 1000000000000.0d;
        }

        public static double MicrobecquerelToBecquerel(double value)
        {
            return value * 9.9999999999999995e-07d;
        }

        public static double BecquerelToMicrobecquerel(double baseValue)
        {
            return baseValue / 9.9999999999999995e-07d;
        }

        public static double MillibecquerelToBecquerel(double value)
        {
            return value * 0.001d;
        }

        public static double BecquerelToMillibecquerel(double baseValue)
        {
            return baseValue / 0.001d;
        }

        public static double PetabecquerelToBecquerel(double value)
        {
            return value * 1000000000000000.0d;
        }

        public static double BecquerelToPetabecquerel(double baseValue)
        {
            return baseValue / 1000000000000000.0d;
        }

        public static double NanobecquerelToBecquerel(double value)
        {
            return value * 1.0000000000000001e-09d;
        }

        public static double BecquerelToNanobecquerel(double baseValue)
        {
            return baseValue / 1.0000000000000001e-09d;
        }

        public static double ExabecquerelToBecquerel(double value)
        {
            return value * 1e+18d;
        }

        public static double BecquerelToExabecquerel(double baseValue)
        {
            return baseValue / 1e+18d;
        }
    }
}

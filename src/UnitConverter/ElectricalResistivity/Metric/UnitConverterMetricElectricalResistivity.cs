namespace UnitConverter.ElectricalResistivity.Metric
{
    public static class UnitConverterMetricElectricalResistivity
    {
        public static double OhmMeterToOhmMeter(double value)
        {
            return value;
        }

        public static double OhmCentimeterToOhmMeter(double value)
        {
            return value * 0.01d;
        }

        public static double OhmMeterToOhmCentimeter(double baseValue)
        {
            return baseValue / 0.01d;
        }

        public static double OhmMillimeterToOhmMeter(double value)
        {
            return value * 0.001d;
        }

        public static double OhmMeterToOhmMillimeter(double baseValue)
        {
            return baseValue / 0.001d;
        }

        public static double MicroohmMeterToOhmMeter(double value)
        {
            return value * 9.9999999999999995e-07d;
        }

        public static double OhmMeterToMicroohmMeter(double baseValue)
        {
            return baseValue / 9.9999999999999995e-07d;
        }

        public static double NanoohmMeterToOhmMeter(double value)
        {
            return value * 1.0000000000000001e-09d;
        }

        public static double OhmMeterToNanoohmMeter(double baseValue)
        {
            return baseValue / 1.0000000000000001e-09d;
        }

        public static double MilliohmMeterToOhmMeter(double value)
        {
            return value * 0.001d;
        }

        public static double OhmMeterToMilliohmMeter(double baseValue)
        {
            return baseValue / 0.001d;
        }

        public static double KiloohmMeterToOhmMeter(double value)
        {
            return value * 1000.0d;
        }

        public static double OhmMeterToKiloohmMeter(double baseValue)
        {
            return baseValue / 1000.0d;
        }

        public static double MicroohmCentimeterToOhmMeter(double value)
        {
            return value * 1e-08d;
        }

        public static double OhmMeterToMicroohmCentimeter(double baseValue)
        {
            return baseValue / 1e-08d;
        }

        public static double PicoohmMeterToOhmMeter(double value)
        {
            return value * 9.9999999999999998e-13d;
        }

        public static double OhmMeterToPicoohmMeter(double baseValue)
        {
            return baseValue / 9.9999999999999998e-13d;
        }

        public static double MegaohmMeterToOhmMeter(double value)
        {
            return value * 1000000.0d;
        }

        public static double OhmMeterToMegaohmMeter(double baseValue)
        {
            return baseValue / 1000000.0d;
        }

        public static double OhmMillimeterSquaredPerMeterToOhmMeter(double value)
        {
            return value * 9.9999999999999995e-07d;
        }

        public static double OhmMeterToOhmMillimeterSquaredPerMeter(double baseValue)
        {
            return baseValue / 9.9999999999999995e-07d;
        }
    }
}

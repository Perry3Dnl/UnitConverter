namespace UnitConverter.Energy.Metric
{
    public static class UnitConverterMetricEnergy
    {
        public static double JouleToJoule(double value)
        {
            return value;
        }

        public static double KilojouleToJoule(double value)
        {
            return value * 1000.0d;
        }

        public static double JouleToKilojoule(double baseValue)
        {
            return baseValue / 1000.0d;
        }

        public static double MegajouleToJoule(double value)
        {
            return value * 1000000.0d;
        }

        public static double JouleToMegajoule(double baseValue)
        {
            return baseValue / 1000000.0d;
        }

        public static double WattHourToJoule(double value)
        {
            return value * 3600.0d;
        }

        public static double JouleToWattHour(double baseValue)
        {
            return baseValue / 3600.0d;
        }

        public static double KilowattHourToJoule(double value)
        {
            return value * 3600000.0d;
        }

        public static double JouleToKilowattHour(double baseValue)
        {
            return baseValue / 3600000.0d;
        }

        public static double CalorieToJoule(double value)
        {
            return value * 4.1840000000000002d;
        }

        public static double JouleToCalorie(double baseValue)
        {
            return baseValue / 4.1840000000000002d;
        }

        public static double KilocalorieToJoule(double value)
        {
            return value * 4184.0d;
        }

        public static double JouleToKilocalorie(double baseValue)
        {
            return baseValue / 4184.0d;
        }

        public static double NanojouleToJoule(double value)
        {
            return value * 1.0000000000000001e-09d;
        }

        public static double JouleToNanojoule(double baseValue)
        {
            return baseValue / 1.0000000000000001e-09d;
        }

        public static double MicrojouleToJoule(double value)
        {
            return value * 9.9999999999999995e-07d;
        }

        public static double JouleToMicrojoule(double baseValue)
        {
            return baseValue / 9.9999999999999995e-07d;
        }

        public static double MillijouleToJoule(double value)
        {
            return value * 0.001d;
        }

        public static double JouleToMillijoule(double baseValue)
        {
            return baseValue / 0.001d;
        }

        public static double GigajouleToJoule(double value)
        {
            return value * 1000000000.0d;
        }

        public static double JouleToGigajoule(double baseValue)
        {
            return baseValue / 1000000000.0d;
        }

        public static double TerajouleToJoule(double value)
        {
            return value * 1000000000000.0d;
        }

        public static double JouleToTerajoule(double baseValue)
        {
            return baseValue / 1000000000000.0d;
        }

        public static double WattSecondToJoule(double value)
        {
            return value * 1.0d;
        }

        public static double JouleToWattSecond(double baseValue)
        {
            return baseValue / 1.0d;
        }
    }
}

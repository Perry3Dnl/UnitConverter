namespace UnitConverter.LinearDensity.Imperial
{
    public static class UnitConverterImperialLinearDensity
    {
        public static double PoundPerFootToKilogramPerMeter(double value)
        {
            return value * 1.4881639435695537d;
        }

        public static double KilogramPerMeterToPoundPerFoot(double baseValue)
        {
            return baseValue / 1.4881639435695537d;
        }

        public static double PoundPerInchToKilogramPerMeter(double value)
        {
            return value * 17.857967322834646d;
        }

        public static double KilogramPerMeterToPoundPerInch(double baseValue)
        {
            return baseValue / 17.857967322834646d;
        }

        public static double OuncePerFootToKilogramPerMeter(double value)
        {
            return value * 0.093010246473097108d;
        }

        public static double KilogramPerMeterToOuncePerFoot(double baseValue)
        {
            return baseValue / 0.093010246473097108d;
        }

        public static double OuncePerInchToKilogramPerMeter(double value)
        {
            return value * 1.1161229576771654d;
        }

        public static double KilogramPerMeterToOuncePerInch(double baseValue)
        {
            return baseValue / 1.1161229576771654d;
        }

        public static double PoundPerYardToKilogramPerMeter(double value)
        {
            return value * 0.49605464785651798d;
        }

        public static double KilogramPerMeterToPoundPerYard(double baseValue)
        {
            return baseValue / 0.49605464785651798d;
        }
    }
}

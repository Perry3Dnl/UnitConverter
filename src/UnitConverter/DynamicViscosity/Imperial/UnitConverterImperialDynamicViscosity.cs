namespace UnitConverter.DynamicViscosity.Imperial
{
    public static class UnitConverterImperialDynamicViscosity
    {
        public static double PoundPerFootSecondToPascalSecond(double value)
        {
            return value * 1.48816394357d;
        }

        public static double PascalSecondToPoundPerFootSecond(double baseValue)
        {
            return baseValue / 1.48816394357d;
        }

        public static double PoundForceSecondPerSquareFootToPascalSecond(double value)
        {
            return value * 47.880258980000001d;
        }

        public static double PascalSecondToPoundForceSecondPerSquareFoot(double baseValue)
        {
            return baseValue / 47.880258980000001d;
        }

        public static double PoundForceSecondPerSquareInchToPascalSecond(double value)
        {
            return value * 6894.7572931679997d;
        }

        public static double PascalSecondToPoundForceSecondPerSquareInch(double baseValue)
        {
            return baseValue / 6894.7572931679997d;
        }

        public static double ReynToPascalSecond(double value)
        {
            return value * 6894.7572931683608d;
        }

        public static double PascalSecondToReyn(double baseValue)
        {
            return baseValue / 6894.7572931683608d;
        }

        public static double PoundPerFootHourToPascalSecond(double value)
        {
            return value * 0.00041337887321327783d;
        }

        public static double PascalSecondToPoundPerFootHour(double baseValue)
        {
            return baseValue / 0.00041337887321327783d;
        }

        public static double SlugPerFootSecondToPascalSecond(double value)
        {
            return value * 47.880258989501307d;
        }

        public static double PascalSecondToSlugPerFootSecond(double baseValue)
        {
            return baseValue / 47.880258989501307d;
        }

        public static double SlugPerFootHourToPascalSecond(double value)
        {
            return value * 0.013300071941528142d;
        }

        public static double PascalSecondToSlugPerFootHour(double baseValue)
        {
            return baseValue / 0.013300071941528142d;
        }

        public static double PoundPerInchSecondToPascalSecond(double value)
        {
            return value * 17.857967322834646d;
        }

        public static double PascalSecondToPoundPerInchSecond(double baseValue)
        {
            return baseValue / 17.857967322834646d;
        }

        public static double PoundPerInchHourToPascalSecond(double value)
        {
            return value * 0.0049605464785651794d;
        }

        public static double PascalSecondToPoundPerInchHour(double baseValue)
        {
            return baseValue / 0.0049605464785651794d;
        }
    }
}

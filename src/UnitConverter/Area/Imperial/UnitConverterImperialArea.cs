namespace UnitConverter.Area.Imperial
{
    public static class UnitConverterImperialArea
    {
        public static double SquareInchToSquareMeter(double value)
        {
            return value * 0.00064515999999999998d;
        }

        public static double SquareMeterToSquareInch(double baseValue)
        {
            return baseValue / 0.00064515999999999998d;
        }

        public static double SquareFootToSquareMeter(double value)
        {
            return value * 0.092903040000000006d;
        }

        public static double SquareMeterToSquareFoot(double baseValue)
        {
            return baseValue / 0.092903040000000006d;
        }

        public static double SquareYardToSquareMeter(double value)
        {
            return value * 0.83612735999999999d;
        }

        public static double SquareMeterToSquareYard(double baseValue)
        {
            return baseValue / 0.83612735999999999d;
        }

        public static double AcreToSquareMeter(double value)
        {
            return value * 4046.8564224000002d;
        }

        public static double SquareMeterToAcre(double baseValue)
        {
            return baseValue / 4046.8564224000002d;
        }

        public static double SquareMileToSquareMeter(double value)
        {
            return value * 2589988.1103360001d;
        }

        public static double SquareMeterToSquareMile(double baseValue)
        {
            return baseValue / 2589988.1103360001d;
        }

        public static double SquareThouToSquareMeter(double value)
        {
            return value * 6.4515999999999997e-10d;
        }

        public static double SquareMeterToSquareThou(double baseValue)
        {
            return baseValue / 6.4515999999999997e-10d;
        }

        public static double CircularMilToSquareMeter(double value)
        {
            return value * 5.0670747909749771e-10d;
        }

        public static double SquareMeterToCircularMil(double baseValue)
        {
            return baseValue / 5.0670747909749771e-10d;
        }
    }
}

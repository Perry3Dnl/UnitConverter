namespace UnitConverter.Density.ImperialUS
{
    public static class UnitConverterImperialUSDensity
    {
        public static double OuncePerUSGallonToKilogramPerCubicMeter(double value)
        {
            return value * 7.4891517070000004d;
        }

        public static double KilogramPerCubicMeterToOuncePerUSGallon(double baseValue)
        {
            return baseValue / 7.4891517070000004d;
        }

        public static double PoundPerUSGallonToKilogramPerCubicMeter(double value)
        {
            return value * 119.82642731689663d;
        }

        public static double KilogramPerCubicMeterToPoundPerUSGallon(double baseValue)
        {
            return baseValue / 119.82642731689663d;
        }

        public static double TonUSPerCubicYardToKilogramPerCubicMeter(double value)
        {
            return value * 1186.5528425158584d;
        }

        public static double KilogramPerCubicMeterToTonUSPerCubicYard(double baseValue)
        {
            return baseValue / 1186.5528425158584d;
        }

        public static double ShortTonPerCubicFootToKilogramPerCubicMeter(double value)
        {
            return value * 32036.926747920279d;
        }

        public static double KilogramPerCubicMeterToShortTonPerCubicFoot(double baseValue)
        {
            return baseValue / 32036.926747920279d;
        }
    }
}

namespace UnitConverter.Density.Imperial
{
    public static class UnitConverterImperialDensity
    {
        public static double PoundPerCubicFootToKilogramPerCubicMeter(double value)
        {
            return value * 16.018463373960142d;
        }

        public static double KilogramPerCubicMeterToPoundPerCubicFoot(double baseValue)
        {
            return baseValue / 16.018463373960142d;
        }

        public static double PoundPerCubicInchToKilogramPerCubicMeter(double value)
        {
            return value * 27679.904710191d;
        }

        public static double KilogramPerCubicMeterToPoundPerCubicInch(double baseValue)
        {
            return baseValue / 27679.904710191d;
        }

        public static double SlugPerCubicFootToKilogramPerCubicMeter(double value)
        {
            return value * 515.37881839320005d;
        }

        public static double KilogramPerCubicMeterToSlugPerCubicFoot(double baseValue)
        {
            return baseValue / 515.37881839320005d;
        }

        public static double OuncePerCubicInchToKilogramPerCubicMeter(double value)
        {
            return value * 1729.994044d;
        }

        public static double KilogramPerCubicMeterToOuncePerCubicInch(double baseValue)
        {
            return baseValue / 1729.994044d;
        }

        public static double OuncePerCubicFootToKilogramPerCubicMeter(double value)
        {
            return value * 1.0011539608725089d;
        }

        public static double KilogramPerCubicMeterToOuncePerCubicFoot(double baseValue)
        {
            return baseValue / 1.0011539608725089d;
        }
    }
}

namespace UnitConverter.MassFlowRate.ImperialUS
{
    public static class UnitConverterImperialUSMassFlowRate
    {
        public static double ShortTonPerHourToKilogramPerSecond(double value)
        {
            return value * 0.25199576111111111d;
        }

        public static double KilogramPerSecondToShortTonPerHour(double baseValue)
        {
            return baseValue / 0.25199576111111111d;
        }

        public static double ShortTonPerSecondToKilogramPerSecond(double value)
        {
            return value * 907.18474000000003d;
        }

        public static double KilogramPerSecondToShortTonPerSecond(double baseValue)
        {
            return baseValue / 907.18474000000003d;
        }

        public static double ShortTonPerDayToKilogramPerSecond(double value)
        {
            return value * 0.01049982337962963d;
        }

        public static double KilogramPerSecondToShortTonPerDay(double baseValue)
        {
            return baseValue / 0.01049982337962963d;
        }
    }
}

namespace UnitConverter.VolumetricFlowRate.ImperialUK
{
    public static class UnitConverterImperialUKVolumetricFlowRate
    {
        public static double ImperialGallonPerMinuteToCubicMeterPerSecond(double value)
        {
            return value * 7.5768166666666671e-05d;
        }

        public static double CubicMeterPerSecondToImperialGallonPerMinute(double baseValue)
        {
            return baseValue / 7.5768166666666671e-05d;
        }

        public static double ImperialGallonPerSecondToCubicMeterPerSecond(double value)
        {
            return value * 0.00454609d;
        }

        public static double CubicMeterPerSecondToImperialGallonPerSecond(double baseValue)
        {
            return baseValue / 0.00454609d;
        }

        public static double ImperialGallonPerHourToCubicMeterPerSecond(double value)
        {
            return value * 1.2628027777777779e-06d;
        }

        public static double CubicMeterPerSecondToImperialGallonPerHour(double baseValue)
        {
            return baseValue / 1.2628027777777779e-06d;
        }

        public static double ImperialFluidOuncePerSecondToCubicMeterPerSecond(double value)
        {
            return value * 2.8413062500000002e-05d;
        }

        public static double CubicMeterPerSecondToImperialFluidOuncePerSecond(double baseValue)
        {
            return baseValue / 2.8413062500000002e-05d;
        }
    }
}

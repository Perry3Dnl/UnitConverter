namespace UnitConverter.Mass.Engineering
{
    public static class UnitConverterEngineeringMass
    {
        public static double SlugToKilogram(double value)
        {
            return value * 14.593902937206d;
        }

        public static double KilogramToSlug(double baseValue)
        {
            return baseValue / 14.593902937206d;
        }
    }
}

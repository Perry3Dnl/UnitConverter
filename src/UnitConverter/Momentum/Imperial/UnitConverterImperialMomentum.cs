namespace UnitConverter.Momentum.Imperial
{
    public static class UnitConverterImperialMomentum
    {
        public static double PoundFootPerSecondToKilogramMeterPerSecond(double value)
        {
            return value * 0.13825495437600002d;
        }

        public static double KilogramMeterPerSecondToPoundFootPerSecond(double baseValue)
        {
            return baseValue / 0.13825495437600002d;
        }

        public static double SlugFootPerSecondToKilogramMeterPerSecond(double value)
        {
            return value * 4.4482216161119998d;
        }

        public static double KilogramMeterPerSecondToSlugFootPerSecond(double baseValue)
        {
            return baseValue / 4.4482216161119998d;
        }

        public static double PoundInchPerSecondToKilogramMeterPerSecond(double value)
        {
            return value * 0.011521246198000001d;
        }

        public static double KilogramMeterPerSecondToPoundInchPerSecond(double baseValue)
        {
            return baseValue / 0.011521246198000001d;
        }

        public static double OunceFootPerSecondToKilogramMeterPerSecond(double value)
        {
            return value * 0.0086409346485000014d;
        }

        public static double KilogramMeterPerSecondToOunceFootPerSecond(double baseValue)
        {
            return baseValue / 0.0086409346485000014d;
        }

        public static double PoundForceSecondToKilogramMeterPerSecond(double value)
        {
            return value * 4.4482216152604996d;
        }

        public static double KilogramMeterPerSecondToPoundForceSecond(double baseValue)
        {
            return baseValue / 4.4482216152604996d;
        }
    }
}

namespace UnitConverter.AngularMomentum.Imperial
{
    public static class UnitConverterImperialAngularMomentum
    {
        public static double PoundSquareFootPerSecondToKilogramSquareMeterPerSecond(double value)
        {
            return value * 0.042140110093804806d;
        }

        public static double KilogramSquareMeterPerSecondToPoundSquareFootPerSecond(double baseValue)
        {
            return baseValue / 0.042140110093804806d;
        }

        public static double SlugSquareFootPerSecondToKilogramSquareMeterPerSecond(double value)
        {
            return value * 1.3558179485909376d;
        }

        public static double KilogramSquareMeterPerSecondToSlugSquareFootPerSecond(double baseValue)
        {
            return baseValue / 1.3558179485909376d;
        }

        public static double PoundSquareInchPerSecondToKilogramSquareMeterPerSecond(double value)
        {
            return value * 0.00029263965342919999d;
        }

        public static double KilogramSquareMeterPerSecondToPoundSquareInchPerSecond(double baseValue)
        {
            return baseValue / 0.00029263965342919999d;
        }

        public static double SlugSquareInchPerSecondToKilogramSquareMeterPerSecond(double value)
        {
            return value * 0.0094154024207703992d;
        }

        public static double KilogramSquareMeterPerSecondToSlugSquareInchPerSecond(double baseValue)
        {
            return baseValue / 0.0094154024207703992d;
        }
    }
}

namespace UnitConverter.SpecificHeatCapacity.Imperial
{
    public static class UnitConverterImperialSpecificHeatCapacity
    {
        public static double BtuPerPoundFahrenheitToJoulePerKilogramKelvin(double value)
        {
            return value * 4186.7999999999993d;
        }

        public static double JoulePerKilogramKelvinToBtuPerPoundFahrenheit(double baseValue)
        {
            return baseValue / 4186.7999999999993d;
        }

        public static double BtuPerPoundRankineToJoulePerKilogramKelvin(double value)
        {
            return value * 4186.7999999999993d;
        }

        public static double JoulePerKilogramKelvinToBtuPerPoundRankine(double baseValue)
        {
            return baseValue / 4186.7999999999993d;
        }

        public static double BtuPerSlugFahrenheitToJoulePerKilogramKelvin(double value)
        {
            return value * 130.12972215340773d;
        }

        public static double JoulePerKilogramKelvinToBtuPerSlugFahrenheit(double baseValue)
        {
            return baseValue / 130.12972215340773d;
        }
    }
}

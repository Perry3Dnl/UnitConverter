namespace UnitConverter.MagnetizingFieldStrength.Scientific
{
    public static class UnitConverterScientificMagnetizingFieldStrength
    {
        public static double OerstedToAmperePerMeter(double value)
        {
            return value * 79.577471545947674d;
        }

        public static double AmperePerMeterToOersted(double baseValue)
        {
            return baseValue / 79.577471545947674d;
        }

        public static double GilbertPerCentimeterToAmperePerMeter(double value)
        {
            return value * 79.577471545947674d;
        }

        public static double AmperePerMeterToGilbertPerCentimeter(double baseValue)
        {
            return baseValue / 79.577471545947674d;
        }
    }
}

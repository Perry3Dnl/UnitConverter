"""Generate full strongly typed Length<T> unit surface from existing Length converter sources.

The old explicit converter classes remain the authoritative source for unit factors. This script
turns their decimal constants into exact rational metadata at build time and emits ordinary C#.
Known core units reuse the hand-written exact implementations.
"""

from pathlib import Path
from decimal import Decimal
from fractions import Fraction
import argparse
import re

ROOT = Path(__file__).resolve().parents[1]
LENGTH_ROOT = ROOT / "src/UnitTools/Length"
ENUM_FILE = LENGTH_ROOT / "UnitToolsLength.cs"
OUTPUT = ROOT / "src/UnitTools/Quantities/Generated/Length.Units.Generated.cs"

CORE_UNITS = {
    "Meter": ("Metres", "FromMetres"),
    "Kilometer": ("Kilometres", "FromKilometres"),
    "Centimeter": ("Centimetres", "FromCentimetres"),
    "Millimeter": ("Millimetres", "FromMillimetres"),
    "Inch": ("Inches", "FromInches"),
    "Foot": ("Feet", "FromFeet"),
    "Yard": ("Yards", "FromYards"),
    "Mile": ("Miles", "FromMiles"),
}

def enum_members():
    text = ENUM_FILE.read_text(encoding="utf-8")
    match = re.search(r"public\s+enum\s+UnitToolsLengthUnit\s*\{([\s\S]*?)\n\s*\}", text)
    if not match:
        raise RuntimeError("Could not find UnitToolsLengthUnit")
    return re.findall(r"^\s*([A-Za-z_][A-Za-z0-9_]*)\s*=", match.group(1), re.MULTILINE)

def factors():
    result = {"Meter": Fraction(1, 1)}
    pattern = re.compile(
        r"public\s+static\s+double\s+([A-Za-z0-9_]+)ToMeter\(double\s+value\)\s*"
        r"\{\s*return\s+value\s*\*\s*([^;]+);",
        re.MULTILINE,
    )
    for path in LENGTH_ROOT.rglob("UnitTools*Length.cs"):
        if path == ENUM_FILE:
            continue
        text = path.read_text(encoding="utf-8")
        for name, literal in pattern.findall(text):
            literal = literal.strip()
            if literal.endswith("d"):
                literal = literal[:-1]
            result[name] = Fraction(Decimal(literal))
    return result

def render():
    units = enum_members()
    factor_map = factors()
    missing = [unit for unit in units if unit not in factor_map]
    if missing:
        raise RuntimeError("Missing Length factors: " + ", ".join(missing))

    lines = [
        "// <auto-generated />",
        "// Generated by scripts/generate_length_quantity.py. Do not edit by hand.",
        "#if NET8_0_OR_GREATER",
        "using System.Numerics;",
        "using UnitTools.Length;",
        "",
        "namespace UnitTools.Quantities",
        "{",
        "    public readonly partial struct Length<T> where T : IFloatingPoint<T>",
        "    {",
    ]

    for unit in units:
        if unit in CORE_UNITS:
            property_name, factory_name = CORE_UNITS[unit]
            lines.extend([
                f"        public T {unit} => {property_name};",
                f"        public static Length<T> From{unit}(T value) => {factory_name}(value);",
                "",
            ])
        else:
            lines.extend([
                f"        public T {unit} => GetFactor(UnitToolsLengthUnit.{unit}).ApplyInverse(_metres);",
                f"        public static Length<T> From{unit}(T value) => new Length<T>(GetFactor(UnitToolsLengthUnit.{unit}).Apply(value));",
                "",
            ])

    lines.extend([
        "        private static global::UnitTools.UnitToolsRational GetFactor(UnitToolsLengthUnit unit)",
        "            => unit switch",
        "            {",
    ])
    for unit in units:
        if unit in CORE_UNITS:
            continue
        factor = factor_map[unit]
        lines.append(
            f'                UnitToolsLengthUnit.{unit} => new global::UnitTools.UnitToolsRational(BigInteger.Parse("{factor.numerator}"), BigInteger.Parse("{factor.denominator}")),'
        )
    lines.extend([
        '                _ => throw new System.ArgumentOutOfRangeException(nameof(unit), unit, "Unsupported Length unit.")',
        "            };",
        "    }",
        "}",
        "#endif",
        "",
    ])
    return "\n".join(lines)

def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    generated = render()

    if args.check:
        if not OUTPUT.exists() or OUTPUT.read_text(encoding="utf-8") != generated:
            raise SystemExit("Generated Length quantity API is out of date. Run scripts/generate_length_quantity.py")
        print("Generated Length quantity API is up to date.")
        return

    OUTPUT.parent.mkdir(parents=True, exist_ok=True)
    OUTPUT.write_text(generated, encoding="utf-8")
    print("Wrote", OUTPUT.relative_to(ROOT))

if __name__ == "__main__":
    main()

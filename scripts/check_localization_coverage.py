"""Generate and verify localization coverage metrics."""

from pathlib import Path
import argparse
import json
import re
import sys

ROOT = Path(__file__).resolve().parents[1]
DEFINITIONS = ROOT / "definitions" / "unit-localization.json"
FAMILY_ENUM = ROOT / "src" / "UnitConverter" / "Catalog" / "UnitConverterFamily.cs"
OUTPUT = ROOT / "docs" / "LocalizationCoverage.md"


def enum_members(text, enum_name):
    match = re.search(
        r"public\s+enum\s+" + re.escape(enum_name) + r"\s*\{([\s\S]*?)\n\s*\}",
        text)
    if not match:
        raise RuntimeError("Could not find enum " + enum_name)

    result = []
    for raw_line in match.group(1).splitlines():
        line = raw_line.split("//", 1)[0].strip()
        if not line:
            continue
        member = re.match(r"([A-Za-z_][A-Za-z0-9_]*)", line)
        if member:
            result.append(member.group(1))
    return result


def catalog_counts():
    family_text = FAMILY_ENUM.read_text(encoding="utf-8")
    families = enum_members(family_text, "UnitConverterFamily")
    counts = {}

    for family in families:
        source = ROOT / "src" / "UnitConverter" / family / ("UnitConverter" + family + ".cs")
        if not source.exists():
            raise RuntimeError("Missing family source: " + str(source))
        counts[family] = len(enum_members(
            source.read_text(encoding="utf-8"),
            "UnitConverter" + family + "Unit"))

    return counts


def render():
    data = json.loads(DEFINITIONS.read_text(encoding="utf-8"))
    counts = catalog_counts()
    total_units = sum(counts.values())
    total_families = len(counts)

    lines = [
        "# Localization coverage",
        "",
        "This file is generated by scripts/check_localization_coverage.py.",
        "Coverage counts only explicit culture vocabulary; invariant fallback does not count as localized coverage.",
        "",
        f"Catalog total: **{total_families} families / {total_units} units**.",
        "",
        "| Culture | Explicit families | Family coverage | Explicit units | Unit coverage |",
        "| --- | ---: | ---: | ---: | ---: |",
    ]

    for culture, family_map in sorted(data.get("cultures", {}).items()):
        family_count = len(family_map)
        unit_count = sum(len(units) for units in family_map.values())
        lines.append(
            f"| {culture} | {family_count} | {family_count / total_families:.1%} | "
            f"{unit_count} | {unit_count / total_units:.1%} |")

    lines.extend(["", "## Per-family explicit coverage", ""])

    for culture, family_map in sorted(data.get("cultures", {}).items()):
        lines.extend([
            f"### {culture}",
            "",
            "| Family | Localized units | Catalog units | Coverage |",
            "| --- | ---: | ---: | ---: |",
        ])
        for family in sorted(family_map):
            localized = len(family_map[family])
            total = counts[family]
            lines.append(
                f"| {family} | {localized} | {total} | {localized / total:.1%} |")
        lines.append("")

    return "\n".join(lines)


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()

    content = render()

    if args.check:
        if not OUTPUT.exists() or OUTPUT.read_text(encoding="utf-8") != content:
            print(
                "Localization coverage report is stale. Run: "
                "python scripts/check_localization_coverage.py",
                file=sys.stderr)
            return 1
        print("Localization coverage report is current.")
        return 0

    OUTPUT.write_text(content, encoding="utf-8")
    print("Generated", OUTPUT.relative_to(ROOT))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())

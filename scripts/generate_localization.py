"""Generate dependency-free localization registrations from curated locale definitions."""

from pathlib import Path
import argparse
import json
import re
import sys

ROOT = Path(__file__).resolve().parents[1]
FAMILY_ENUM = ROOT / "src/UnitTools/Catalog/UnitToolsFamily.cs"
DEFINITIONS = ROOT / "definitions/unit-localization.json"
OUTPUT = ROOT / "src/UnitTools/Common/UnitToolsLocalization.Generated.cs"
COVERAGE_OUTPUT = ROOT / "docs/LocalizationCoverage.md"

def enum_body(text, enum_name):
    match = re.search(r"public\s+enum\s+" + re.escape(enum_name) + r"\s*\{([\s\S]*?)\n\s*\}", text)
    if not match:
        raise RuntimeError("Could not find enum " + enum_name)
    return match.group(1)

def enum_members(text, enum_name):
    result = []
    for raw_line in enum_body(text, enum_name).splitlines():
        line = raw_line.split("//", 1)[0].strip()
        if not line:
            continue
        match = re.match(r"([A-Za-z_][A-Za-z0-9_]*)\s*(?:=\s*[^,]+)?\s*,?$", line)
        if match:
            result.append(match.group(1))
    return result

def csharp_string(value):
    return '"' + value.replace("\\", "\\\\").replace('"', '\\"') + '"'

def validate_model(data):
    family_text = FAMILY_ENUM.read_text(encoding="utf-8")
    families = set(enum_members(family_text, "UnitToolsFamily"))

    cultures = data.get("cultures", {})
    complete_families = data.get("completeFamilies", {})
    for culture, family_map in cultures.items():
        if not culture:
            raise RuntimeError("Built-in localization culture names must be non-empty.")
        for family, unit_map in family_map.items():
            if family not in families:
                raise RuntimeError("Localization references unknown family " + family)
            source = ROOT / "src/UnitTools" / family / ("UnitTools" + family + ".cs")
            if not source.exists():
                raise RuntimeError("Missing converter source for " + family)
            units = set(enum_members(source.read_text(encoding="utf-8"), "UnitTools" + family + "Unit"))
            unknown = sorted(set(unit_map) - units)
            if unknown:
                raise RuntimeError(
                    "Localization references unknown " + family + " units: " + ", ".join(unknown)
                )
            for unit, entry in unit_map.items():
                display = entry.get("displayName")
                if not isinstance(display, str) or not display.strip():
                    raise RuntimeError(culture + "/" + family + "/" + unit + " requires displayName")
                aliases = entry.get("aliases", [])
                if not isinstance(aliases, list) or any(not isinstance(x, str) or not x.strip() for x in aliases):
                    raise RuntimeError(culture + "/" + family + "/" + unit + " has invalid aliases")

            if family in set(complete_families.get(culture, [])):
                missing = sorted(units - set(unit_map))
                if missing:
                    raise RuntimeError(
                        culture + "/" + family + " is marked complete but is missing: " +
                        ", ".join(missing)
                    )

    for culture, declared in complete_families.items():
        if culture not in cultures:
            raise RuntimeError("Completeness metadata references unknown culture " + culture)
        unknown = sorted(set(declared) - set(cultures[culture]))
        if unknown:
            raise RuntimeError(
                "Completeness metadata references unlocalized families for " +
                culture + ": " + ", ".join(unknown)
            )

    return cultures

def render(cultures):
    lines = [
        "// <auto-generated />",
        "// Generated by scripts/generate_localization.py. Do not edit by hand.",
        "namespace UnitTools",
        "{",
        "    using System.Globalization;",
        "",
        "    internal static class UnitToolsBuiltInLocalization",
        "    {",
        "        public static void RegisterAll()",
        "        {",
    ]
    for culture in sorted(cultures):
        lines.append("            CultureInfo culture = CultureInfo.GetCultureInfo(" + csharp_string(culture) + ");")
        for family in sorted(cultures[culture]):
            enum_type = "global::UnitTools." + family + ".UnitTools" + family + "Unit"
            for unit, entry in cultures[culture][family].items():
                aliases = list(entry.get("aliases", []))
                args = ", ".join(csharp_string(x) for x in aliases)
                suffix = ", " + args if args else ""
                lines.extend([
                    "            UnitToolsLocalization.Register(",
                    "                culture,",
                    "                " + enum_type + "." + unit + ",",
                    "                " + csharp_string(entry["displayName"]) + suffix + ");",
                ])
        lines.append("")
    lines.extend([
        "        }",
        "    }",
        "}",
        "",
    ])
    return "\n".join(lines)

def render_coverage(data, cultures):
    complete_families = data.get("completeFamilies", {})
    lines = [
        "# Localization coverage",
        "",
        "Generated by `scripts/generate_localization.py`. A family is marked **complete** only when every registered unit in that family has an explicit locale entry.",
        "",
        "| Culture | Family | Localized units | Catalog units | Status |",
        "| --- | --- | ---: | ---: | --- |",
    ]

    for culture in sorted(cultures):
        completed = set(complete_families.get(culture, []))
        for family in sorted(cultures[culture]):
            source = ROOT / "src/UnitTools" / family / ("UnitTools" + family + ".cs")
            catalog_units = enum_members(
                source.read_text(encoding="utf-8"),
                "UnitTools" + family + "Unit")
            localized = len(cultures[culture][family])
            status = "complete" if family in completed else "partial"
            lines.append(
                "| " + culture + " | " + family + " | " +
                str(localized) + " | " + str(len(catalog_units)) +
                " | " + status + " |"
            )

    lines.append("")
    return "\n".join(lines)

def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()

    data = json.loads(DEFINITIONS.read_text(encoding="utf-8"))
    cultures = validate_model(data)
    output = render(cultures)
    coverage = render_coverage(data, cultures)

    if args.check:
        stale = []
        if not OUTPUT.exists() or OUTPUT.read_text(encoding="utf-8") != output:
            stale.append(str(OUTPUT.relative_to(ROOT)))
        if not COVERAGE_OUTPUT.exists() or COVERAGE_OUTPUT.read_text(encoding="utf-8") != coverage:
            stale.append(str(COVERAGE_OUTPUT.relative_to(ROOT)))
        if stale:
            print(
                "Generated localization output is out of date: " + ", ".join(stale) +
                ". Run: python scripts/generate_localization.py",
                file=sys.stderr,
            )
            return 1
        print("Generated localization source and coverage report are up to date.")
        return 0

    OUTPUT.write_text(output, encoding="utf-8")
    COVERAGE_OUTPUT.write_text(coverage, encoding="utf-8")
    print("Generated", OUTPUT.relative_to(ROOT))
    print("Generated", COVERAGE_OUTPUT.relative_to(ROOT))
    return 0

if __name__ == "__main__":
    raise SystemExit(main())

"""Generate the additional UnitConverter family APIs from definitions/additional-families.json.

The checked-in generated files preserve the library's explicit per-family/per-unit API while
keeping scale factors, symbols, unit-system metadata, exact rational scales and catalog
registration in one auditable definition file.
"""

from pathlib import Path
from decimal import Decimal
from fractions import Fraction
import argparse
import json
import re
import sys

ROOT = Path(__file__).resolve().parents[1]
DEFINITIONS = ROOT / "definitions/additional-families.json"
SRC = ROOT / "src/UnitConverter"
CATALOG_OUTPUT = SRC / "Catalog/UnitConverterAdditionalFamilyDescriptors.Generated.cs"
QUANTITY_OUTPUT_DIR = SRC / "Quantities/GeneratedAdditional"

def fraction(text):
    text = str(text).strip()
    if "/" in text:
        left, right = text.split("/", 1)
        return Fraction(int(left.strip()), int(right.strip()))
    return Fraction(Decimal(text))

def humanize(name):
    text = re.sub(r"([A-Z]+)([A-Z][a-z])", r"\1 \2", name)
    text = re.sub(r"([a-z0-9])([A-Z])", r"\1 \2", text)
    return " ".join(text.split())

def cs(value):
    return '"' + value.replace("\\", "\\\\").replace('"', '\\"') + '"'

def rational_expr(value):
    value = fraction(value)
    return (
        "new global::UnitConverter.UnitConverterRational("
        f'BigInteger.Parse("{value.numerator}"), '
        f'BigInteger.Parse("{value.denominator}"))'
    )

def double_factor(value):
    value = fraction(value)
    max_int64 = (1 << 63) - 1
    if abs(value.numerator) <= max_int64 and value.denominator <= max_int64:
        return f"((double){value.numerator} / (double){value.denominator})"
    return format(float(value), ".17g") + "d"

def render_converter(family):
    name = family["name"]
    enum_name = "UnitConverter" + name + "Unit"
    class_name = "UnitConverter" + name
    units = family["units"]
    base = units[0]["name"]
    lines = [
        "// <auto-generated />",
        "// Generated by scripts/generate_additional_families.py. Do not edit by hand.",
        f"namespace UnitConverter.{name}",
        "{",
        "    using System.Numerics;",
        "",
        f"    public enum {enum_name}",
        "    {",
    ]
    for index, unit in enumerate(units):
        lines.append(f'        {unit["name"]} = {index},')
    lines.extend([
        "    }",
        "",
        f"    public static class {class_name}",
        "    {",
        f"        public static double Convert(double value, {enum_name} from, {enum_name} to)",
        "        {",
        f"            double baseValue = To{base}(value, from);",
        f"            return From{base}(baseValue, to);",
        "        }",
        "",
        f"        public static double To{base}(double value, {enum_name} from)",
        "        {",
        "            switch (from)",
        "            {",
    ])
    for unit in units:
        u = unit["name"]
        lines.append(f"                case {enum_name}.{u}:")
        lines.append(f"                    return {u}To{base}(value);")
    lines.extend([
        "                default:",
        f'                    throw new System.ArgumentOutOfRangeException(nameof(from), from, "Unsupported {humanize(name).lower()} unit.");',
        "            }",
        "        }",
        "",
        f"        public static double From{base}(double baseValue, {enum_name} to)",
        "        {",
        "            switch (to)",
        "            {",
    ])
    for unit in units:
        u = unit["name"]
        lines.append(f"                case {enum_name}.{u}:")
        lines.append(f"                    return {base}To{u}(baseValue);")
    lines.extend([
        "                default:",
        f'                    throw new System.ArgumentOutOfRangeException(nameof(to), to, "Unsupported {humanize(name).lower()} unit.");',
        "            }",
        "        }",
        "",
    ])
    for unit in units:
        u = unit["name"]
        factor = double_factor(unit["factor"])
        if u == base:
            lines.extend([
                f"        public static double {base}To{base}(double value) => value;",
                "",
            ])
        else:
            lines.extend([
                f"        public static double {u}To{base}(double value) => value * {factor};",
                f"        public static double {base}To{u}(double value) => value / {factor};",
                "",
            ])
    lines.extend([
        f"        public static string GetSymbol({enum_name} unit)",
        "        {",
        "            switch (unit)",
        "            {",
    ])
    for unit in units:
        lines.append(f'                case {enum_name}.{unit["name"]}: return {cs(unit["symbol"])};')
    lines.extend([
        '                default: return "?";',
        "            }",
        "        }",
        "",
        f"        public static string GetDisplayName({enum_name} unit)",
        "        {",
        "            switch (unit)",
        "            {",
    ])
    for unit in units:
        display = unit.get("displayName") or humanize(unit["name"])
        lines.append(f'                case {enum_name}.{unit["name"]}: return {cs(display)};')
    lines.extend([
        "                default: return unit.ToString();",
        "            }",
        "        }",
        "",
        f"        public static global::UnitConverter.UnitConverterUnitSystem GetUnitSystem({enum_name} unit)",
        "        {",
        "            switch (unit)",
        "            {",
    ])
    for unit in units:
        lines.append(
            f'                case {enum_name}.{unit["name"]}: '
            f'return global::UnitConverter.UnitConverterUnitSystem.{unit["system"]};'
        )
    lines.extend([
        "                default: return global::UnitConverter.UnitConverterUnitSystem.Unknown;",
        "            }",
        "        }",
        "",
        f"        public static {enum_name}[] GetUnitsForSystem(global::UnitConverter.UnitConverterUnitSystem unitSystem)",
        "        {",
        "            switch (unitSystem)",
        "            {",
    ])
    systems = []
    for unit in units:
        if unit["system"] not in systems:
            systems.append(unit["system"])
    for system in systems:
        members = ", ".join(f"{enum_name}.{u['name']}" for u in units if u["system"] == system)
        lines.append(f"                case global::UnitConverter.UnitConverterUnitSystem.{system}:")
        lines.append(f"                    return new[] {{ {members} }};")
    all_members = ", ".join(f"{enum_name}.{u['name']}" for u in units)
    lines.extend([
        "                default:",
        f"                    return new[] {{ {all_members} }};",
        "            }",
        "        }",
        "",
        f"        internal static global::UnitConverter.UnitConverterRational GetFactor({enum_name} unit)",
        "        {",
        "            switch (unit)",
        "            {",
    ])
    for unit in units:
        lines.append(f"                case {enum_name}.{unit['name']}:")
        lines.append(f"                    return {rational_expr(unit['factor'])};")
    lines.extend([
        "                default:",
        f'                    throw new System.ArgumentOutOfRangeException(nameof(unit), unit, "Unsupported {humanize(name).lower()} unit.");',
        "            }",
        "        }",
        "    }",
        "}",
        "",
    ])
    return "\n".join(lines)

def render_extensions(family):
    name = family["name"]
    enum_name = "UnitConverter" + name + "Unit"
    class_name = "UnitConverter" + name
    lines = [
        "// <auto-generated />",
        "// Generated by scripts/generate_additional_families.py. Do not edit by hand.",
        f"namespace UnitConverter.{name}",
        "{",
        f"    public static class {class_name}Extensions",
        "    {",
        f"        public static double Convert(this double value, {enum_name} from, {enum_name} to)",
        f"            => {class_name}.Convert(value, from, to);",
        f"        public static float Convert(this float value, {enum_name} from, {enum_name} to)",
        f"            => (float){class_name}.Convert(value, from, to);",
        f"        public static decimal Convert(this decimal value, {enum_name} from, {enum_name} to)",
        "            => global::UnitConverter.UnitConverterExact.Convert(value, from, to);",
    ]
    for numeric in ["byte", "sbyte", "short", "ushort", "int", "uint", "long", "ulong"]:
        lines.append(
            f"        public static double Convert(this {numeric} value, {enum_name} from, {enum_name} to) "
            f"=> {class_name}.Convert(value, from, to);"
        )
    lines.extend(["    }", "}", ""])
    return "\n".join(lines)

def render_quantity(family):
    name = family["name"]
    enum_name = "UnitConverter" + name + "Unit"
    converter_name = "UnitConverter" + name
    units = family["units"]
    base = units[0]["name"]
    base_symbol = units[0]["symbol"]
    error_name = humanize(name).lower()

    lines = [
        "// <auto-generated />",
        "// Generated by scripts/generate_additional_families.py. Do not edit by hand.",
        "#if NET8_0_OR_GREATER",
        "using System;",
        "using System.Numerics;",
        f"using UnitConverter.{name};",
        "",
        "namespace UnitConverter.Quantities",
        "{",
        f"    /// <summary>Strongly typed {humanize(name)} quantity backed by the family base unit.</summary>",
        f"    public readonly partial struct {name}<T> :",
        f"        IEquatable<{name}<T>>,",
        f"        IComparable<{name}<T>>,",
        "        IFormattable,",
        "        ISpanFormattable,",
        f"        IParsable<{name}<T>>,",
        f"        ISpanParsable<{name}<T>>",
        "        where T : IFloatingPoint<T>",
        "    {",
        f"        private static readonly {enum_name} BaseUnit = {enum_name}.{base};",
        "        private readonly T _baseValue;",
        "",
        f"        private {name}(T baseValue) => _baseValue = baseValue;",
        "",
        f"        public T {base} => _baseValue;",
    ]

    for unit in units[1:]:
        lines.append(
            f"        public T {unit['name']} => UnitConverterNumeric.Convert(_baseValue, BaseUnit, {enum_name}.{unit['name']});"
        )

    lines.extend([""])
    for unit in units:
        u = unit["name"]
        if u == base:
            lines.append(f"        public static {name}<T> From{u}(T value) => new {name}<T>(value);")
        else:
            lines.append(
                f"        public static {name}<T> From{u}(T value) => "
                f"new {name}<T>(UnitConverterNumeric.Convert(value, {enum_name}.{u}, BaseUnit));"
            )

    lines.extend([
        "",
        f"        public static {name}<T> From(T value, {enum_name} unit)",
        f"            => new {name}<T>(UnitConverterNumeric.Convert(value, unit, BaseUnit));",
        "",
        f"        public T In({enum_name} unit)",
        "            => UnitConverterNumeric.Convert(_baseValue, BaseUnit, unit);",
        "",
        f"        public static {name}<T> operator +({name}<T> left, {name}<T> right)",
        f"            => new {name}<T>(left._baseValue + right._baseValue);",
        f"        public static {name}<T> operator -({name}<T> left, {name}<T> right)",
        f"            => new {name}<T>(left._baseValue - right._baseValue);",
        f"        public static {name}<T> operator -({name}<T> value)",
        f"            => new {name}<T>(-value._baseValue);",
        f"        public static {name}<T> operator *({name}<T> quantity, T scalar)",
        f"            => new {name}<T>(quantity._baseValue * scalar);",
        f"        public static {name}<T> operator *(T scalar, {name}<T> quantity)",
        "            => quantity * scalar;",
        f"        public static {name}<T> operator /({name}<T> quantity, T scalar)",
        f"            => new {name}<T>(quantity._baseValue / scalar);",
        f"        public static T operator /({name}<T> left, {name}<T> right)",
        "            => left._baseValue / right._baseValue;",
        "",
        f"        public static bool operator ==({name}<T> left, {name}<T> right) => left.Equals(right);",
        f"        public static bool operator !=({name}<T> left, {name}<T> right) => !left.Equals(right);",
        f"        public static bool operator <({name}<T> left, {name}<T> right) => left._baseValue < right._baseValue;",
        f"        public static bool operator >({name}<T> left, {name}<T> right) => left._baseValue > right._baseValue;",
        f"        public static bool operator <=({name}<T> left, {name}<T> right) => left._baseValue <= right._baseValue;",
        f"        public static bool operator >=({name}<T> left, {name}<T> right) => left._baseValue >= right._baseValue;",
        "",
        f"        public bool Equals({name}<T> other) => _baseValue == other._baseValue;",
        f"        public override bool Equals(object obj) => obj is {name}<T> other && Equals(other);",
        "        public override int GetHashCode() => _baseValue.GetHashCode();",
        f"        public int CompareTo({name}<T> other) => _baseValue.CompareTo(other._baseValue);",
        "",
        "        public override string ToString() => ToString(null, null);",
        "        public string ToString(string format, IFormatProvider formatProvider)",
        f'            => _baseValue.ToString(format, formatProvider) + " " + {cs(base_symbol)};',
        "",
        "        public bool TryFormat(",
        "            Span<char> destination,",
        "            out int charsWritten,",
        "            ReadOnlySpan<char> format,",
        "            IFormatProvider provider)",
        "        {",
        "            charsWritten = 0;",
        "            if (!_baseValue.TryFormat(destination, out int valueChars, format, provider))",
        "                return false;",
        f"            ReadOnlySpan<char> symbol = {cs(base_symbol)}.AsSpan();",
        "            int required = valueChars + 1 + symbol.Length;",
        "            if (destination.Length < required)",
        "                return false;",
        "            destination[valueChars] = ' ';",
        "            symbol.CopyTo(destination.Slice(valueChars + 1));",
        "            charsWritten = required;",
        "            return true;",
        "        }",
        "",
        f"        public static {name}<T> Parse(string s, IFormatProvider provider)",
        "            => Parse(s.AsSpan(), provider);",
        f"        public static {name}<T> Parse(ReadOnlySpan<char> s, IFormatProvider provider)",
        "        {",
        f"            if (!TryParse(s, provider, out {name}<T> result))",
        f'                throw new FormatException("Input was not a valid {error_name} quantity.");',
        "            return result;",
        "        }",
        f"        public static bool TryParse(string s, IFormatProvider provider, out {name}<T> result)",
        "            => TryParse(s.AsSpan(), provider, out result);",
        f"        public static bool TryParse(ReadOnlySpan<char> s, IFormatProvider provider, out {name}<T> result)",
        "        {",
        "            result = default;",
        "            if (!QuantityText.TryParseValueAndUnit(s, provider, out T value, out ReadOnlySpan<char> unit))",
        "                return false;",
    ])

    for index, unit in enumerate(units):
        prefix = "if" if index == 0 else "else if"
        lines.append(
            f"            {prefix} (unit.Equals({cs(unit['symbol'])}.AsSpan(), StringComparison.OrdinalIgnoreCase)) "
            f"result = From{unit['name']}(value);"
        )

    lines.extend([
        "            else return false;",
        "            return true;",
        "        }",
        "    }",
        "",
        f"    public static class {name}Methods",
        "    {",
    ])

    for unit in units:
        u = unit["name"]
        lines.extend([
            f"        public static {name}<T> From{u}<T>(T value) where T : IFloatingPoint<T>",
            f"            => {name}<T>.From{u}(value);",
            f"        public static T To{u}<T>(this {name}<T> quantity) where T : IFloatingPoint<T>",
            f"            => quantity.{u};",
            "",
        ])

    lines.extend([
        f"        public static {name}<T> From<T>(T value, {enum_name} unit) where T : IFloatingPoint<T>",
        f"            => {name}<T>.From(value, unit);",
        f"        public static T In<T>(this {name}<T> quantity, {enum_name} unit) where T : IFloatingPoint<T>",
        "            => quantity.In(unit);",
        f"        public static T Convert<T>(T value, {enum_name} from, {enum_name} to) where T : IFloatingPoint<T>",
        "            => From(value, from).In(to);",
        "    }",
        "}",
        "#endif",
        "",
    ])
    return "\n".join(lines)

def render_catalog(model):
    lines = [
        "// <auto-generated />",
        "// Generated by scripts/generate_additional_families.py. Do not edit by hand.",
        "namespace UnitConverter.Catalog",
        "{",
        "    public static partial class UnitConverterCatalog",
        "    {",
        "        private static UnitConverterFamilyDescriptor[] GetAdditionalFamilyDescriptors()",
        "        {",
        "            return new UnitConverterFamilyDescriptor[]",
        "            {",
    ]
    for family in model["families"]:
        name = family["name"]
        base = family["units"][0]["name"]
        enum_type = f"UnitConverter.{name}.UnitConverter{name}Unit"
        converter = f"UnitConverter.{name}.UnitConverter{name}"
        lines.append(
            f'                Create<{enum_type}>(UnitConverterFamily.{name}, "{name}", "{base}", '
            f"{converter}.GetSymbol, {converter}.GetDisplayName, {converter}.Convert, "
            f"getExactScale: {converter}.GetFactor),"
        )
    lines.extend([
        "            };",
        "        }",
        "    }",
        "}",
        "",
    ])
    return "\n".join(lines)

def rendered_files(model):
    files = {CATALOG_OUTPUT: render_catalog(model)}
    for family in model["families"]:
        name = family["name"]
        directory = SRC / name
        files[directory / ("UnitConverter" + name + ".cs")] = render_converter(family)
        files[directory / ("UnitConverter" + name + "Extensions.cs")] = render_extensions(family)
        files[QUANTITY_OUTPUT_DIR / (name + ".Generated.cs")] = render_quantity(family)
    return files

def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    model = json.loads(DEFINITIONS.read_text(encoding="utf-8"))
    files = rendered_files(model)

    if args.check:
        stale = [
            path for path, output in files.items()
            if not path.exists() or path.read_text(encoding="utf-8") != output
        ]
        if stale:
            print(
                "Generated additional family source is out of date: " +
                ", ".join(str(path.relative_to(ROOT)) for path in stale),
                file=sys.stderr,
            )
            return 1
        print("Generated additional family source is up to date.")
        return 0

    for path, output in files.items():
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(output, encoding="utf-8")
        print("Generated", path.relative_to(ROOT))
    return 0

if __name__ == "__main__":
    raise SystemExit(main())

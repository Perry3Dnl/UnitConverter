"""Generate the additional UnitConverter family APIs from definitions/additional-families.json.

The checked-in generated files preserve the library's explicit per-family/per-unit API while
keeping scale factors, symbols, unit-system metadata, exact rational scales and catalog
registration in one auditable definition file.
"""

from pathlib import Path
from decimal import Decimal
from fractions import Fraction
import argparse
import json
import re
import sys

ROOT = Path(__file__).resolve().parents[1]
DEFINITIONS = ROOT / "definitions/additional-families.json"
SRC = ROOT / "src/UnitConverter"
CATALOG_OUTPUT = SRC / "Catalog/UnitConverterAdditionalFamilyDescriptors.Generated.cs"

def fraction(text):
    text = str(text).strip()
    if "/" in text:
        left, right = text.split("/", 1)
        return Fraction(int(left.strip()), int(right.strip()))
    return Fraction(Decimal(text))

def humanize(name):
    text = re.sub(r"([A-Z]+)([A-Z][a-z])", r"\1 \2", name)
    text = re.sub(r"([a-z0-9])([A-Z])", r"\1 \2", text)
    return " ".join(text.split())

def cs(value):
    return '"' + value.replace("\\", "\\\\").replace('"', '\\"') + '"'

def rational_expr(value):
    value = fraction(value)
    return (
        "new global::UnitConverter.UnitConverterRational("
        f'BigInteger.Parse("{value.numerator}"), '
        f'BigInteger.Parse("{value.denominator}"))'
    )

def double_factor(value):
    value = fraction(value)
    return f"((double){value.numerator} / (double){value.denominator})"

def render_converter(family):
    name = family["name"]
    enum_name = "UnitConverter" + name + "Unit"
    class_name = "UnitConverter" + name
    units = family["units"]
    base = units[0]["name"]
    lines = [
        "// <auto-generated />",
        "// Generated by scripts/generate_additional_families.py. Do not edit by hand.",
        f"namespace UnitConverter.{name}",
        "{",
        "    using System.Numerics;",
        "",
        f"    public enum {enum_name}",
        "    {",
    ]
    for index, unit in enumerate(units):
        lines.append(f'        {unit["name"]} = {index},')
    lines.extend([
        "    }",
        "",
        f"    public static class {class_name}",
        "    {",
        f"        public static double Convert(double value, {enum_name} from, {enum_name} to)",
        "        {",
        f"            double baseValue = To{base}(value, from);",
        f"            return From{base}(baseValue, to);",
        "        }",
        "",
        f"        public static double To{base}(double value, {enum_name} from)",
        "        {",
        "            switch (from)",
        "            {",
    ])
    for unit in units:
        u = unit["name"]
        lines.append(f"                case {enum_name}.{u}:")
        lines.append(f"                    return {u}To{base}(value);")
    lines.extend([
        "                default:",
        f'                    throw new System.ArgumentOutOfRangeException(nameof(from), from, "Unsupported {humanize(name).lower()} unit.");',
        "            }",
        "        }",
        "",
        f"        public static double From{base}(double baseValue, {enum_name} to)",
        "        {",
        "            switch (to)",
        "            {",
    ])
    for unit in units:
        u = unit["name"]
        lines.append(f"                case {enum_name}.{u}:")
        lines.append(f"                    return {base}To{u}(baseValue);")
    lines.extend([
        "                default:",
        f'                    throw new System.ArgumentOutOfRangeException(nameof(to), to, "Unsupported {humanize(name).lower()} unit.");',
        "            }",
        "        }",
        "",
    ])
    for unit in units:
        u = unit["name"]
        factor = double_factor(unit["factor"])
        if u == base:
            lines.extend([
                f"        public static double {base}To{base}(double value) => value;",
                "",
            ])
        else:
            lines.extend([
                f"        public static double {u}To{base}(double value) => value * {factor};",
                f"        public static double {base}To{u}(double value) => value / {factor};",
                "",
            ])
    lines.extend([
        f"        public static string GetSymbol({enum_name} unit)",
        "        {",
        "            switch (unit)",
        "            {",
    ])
    for unit in units:
        lines.append(f'                case {enum_name}.{unit["name"]}: return {cs(unit["symbol"])};')
    lines.extend([
        '                default: return "?";',
        "            }",
        "        }",
        "",
        f"        public static string GetDisplayName({enum_name} unit)",
        "        {",
        "            switch (unit)",
        "            {",
    ])
    for unit in units:
        display = unit.get("displayName") or humanize(unit["name"])
        lines.append(f'                case {enum_name}.{unit["name"]}: return {cs(display)};')
    lines.extend([
        "                default: return unit.ToString();",
        "            }",
        "        }",
        "",
        f"        public static global::UnitConverter.UnitConverterUnitSystem GetUnitSystem({enum_name} unit)",
        "        {",
        "            switch (unit)",
        "            {",
    ])
    for unit in units:
        lines.append(
            f'                case {enum_name}.{unit["name"]}: '
            f'return global::UnitConverter.UnitConverterUnitSystem.{unit["system"]};'
        )
    lines.extend([
        "                default: return global::UnitConverter.UnitConverterUnitSystem.Unknown;",
        "            }",
        "        }",
        "",
        f"        public static {enum_name}[] GetUnitsForSystem(global::UnitConverter.UnitConverterUnitSystem unitSystem)",
        "        {",
        "            switch (unitSystem)",
        "            {",
    ])
    systems = []
    for unit in units:
        if unit["system"] not in systems:
            systems.append(unit["system"])
    for system in systems:
        members = ", ".join(f"{enum_name}.{u['name']}" for u in units if u["system"] == system)
        lines.append(f"                case global::UnitConverter.UnitConverterUnitSystem.{system}:")
        lines.append(f"                    return new[] {{ {members} }};")
    all_members = ", ".join(f"{enum_name}.{u['name']}" for u in units)
    lines.extend([
        "                default:",
        f"                    return new[] {{ {all_members} }};",
        "            }",
        "        }",
        "",
        f"        internal static global::UnitConverter.UnitConverterRational GetFactor({enum_name} unit)",
        "        {",
        "            switch (unit)",
        "            {",
    ])
    for unit in units:
        lines.append(f"                case {enum_name}.{unit['name']}:")
        lines.append(f"                    return {rational_expr(unit['factor'])};")
    lines.extend([
        "                default:",
        f'                    throw new System.ArgumentOutOfRangeException(nameof(unit), unit, "Unsupported {humanize(name).lower()} unit.");',
        "            }",
        "        }",
        "    }",
        "}",
        "",
    ])
    return "\n".join(lines)

def render_extensions(family):
    name = family["name"]
    enum_name = "UnitConverter" + name + "Unit"
    class_name = "UnitConverter" + name
    lines = [
        "// <auto-generated />",
        "// Generated by scripts/generate_additional_families.py. Do not edit by hand.",
        f"namespace UnitConverter.{name}",
        "{",
        f"    public static class {class_name}Extensions",
        "    {",
        f"        public static double Convert(this double value, {enum_name} from, {enum_name} to)",
        f"            => {class_name}.Convert(value, from, to);",
        f"        public static float Convert(this float value, {enum_name} from, {enum_name} to)",
        f"            => (float){class_name}.Convert(value, from, to);",
        f"        public static decimal Convert(this decimal value, {enum_name} from, {enum_name} to)",
        "            => global::UnitConverter.UnitConverterExact.Convert(value, from, to);",
    ]
    for numeric in ["byte", "sbyte", "short", "ushort", "int", "uint", "long", "ulong"]:
        lines.append(
            f"        public static double Convert(this {numeric} value, {enum_name} from, {enum_name} to) "
            f"=> {class_name}.Convert(value, from, to);"
        )
    lines.extend(["    }", "}", ""])
    return "\n".join(lines)

def render_catalog(model):
    lines = [
        "// <auto-generated />",
        "// Generated by scripts/generate_additional_families.py. Do not edit by hand.",
        "namespace UnitConverter.Catalog",
        "{",
        "    public static partial class UnitConverterCatalog",
        "    {",
        "        private static UnitConverterFamilyDescriptor[] GetAdditionalFamilyDescriptors()",
        "        {",
        "            return new UnitConverterFamilyDescriptor[]",
        "            {",
    ]
    for family in model["families"]:
        name = family["name"]
        base = family["units"][0]["name"]
        enum_type = f"UnitConverter.{name}.UnitConverter{name}Unit"
        converter = f"UnitConverter.{name}.UnitConverter{name}"
        lines.append(
            f'                Create<{enum_type}>(UnitConverterFamily.{name}, "{name}", "{base}", '
            f"{converter}.GetSymbol, {converter}.GetDisplayName, {converter}.Convert, "
            f"getExactScale: {converter}.GetFactor),"
        )
    lines.extend([
        "            };",
        "        }",
        "    }",
        "}",
        "",
    ])
    return "\n".join(lines)

def rendered_files(model):
    files = {CATALOG_OUTPUT: render_catalog(model)}
    for family in model["families"]:
        name = family["name"]
        directory = SRC / name
        files[directory / ("UnitConverter" + name + ".cs")] = render_converter(family)
        files[directory / ("UnitConverter" + name + "Extensions.cs")] = render_extensions(family)
    return files

def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    model = json.loads(DEFINITIONS.read_text(encoding="utf-8"))
    files = rendered_files(model)

    if args.check:
        stale = [
            path for path, output in files.items()
            if not path.exists() or path.read_text(encoding="utf-8") != output
        ]
        if stale:
            print(
                "Generated additional family source is out of date: " +
                ", ".join(str(path.relative_to(ROOT)) for path in stale),
                file=sys.stderr,
            )
            return 1
        print("Generated additional family source is up to date.")
        return 0

    for path, output in files.items():
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(output, encoding="utf-8")
        print("Generated", path.relative_to(ROOT))
    return 0

if __name__ == "__main__":
    raise SystemExit(main())

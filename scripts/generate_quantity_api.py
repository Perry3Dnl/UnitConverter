"""Generate explicit strongly typed quantity helper methods from definitions/quantity-api.json.

The generated API intentionally remains per-family and per-unit. This generator reduces
maintenance boilerplate; it does not collapse the public API into a generic runtime converter.
"""

from pathlib import Path
import argparse
import json

ROOT = Path(__file__).resolve().parents[1]
DEFINITIONS = ROOT / "definitions/quantity-api.json"
OUTPUT_DIR = ROOT / "src/UnitConverter/Quantities/Generated"

def render_family(family_name, family):
    quantity_type = family["type"]
    helper_name = quantity_type + "Methods"
    lines = [
        "// <auto-generated />",
        "// Generated by scripts/generate_quantity_api.py. Do not edit by hand.",
        "#if NET8_0_OR_GREATER",
        "using System.Numerics;",
        "",
        "namespace UnitConverter.Quantities",
        "{",
        f"    public static class {helper_name}",
        "    {",
    ]

    for unit in family["units"]:
        property_name = unit["name"]
        factory_name = unit["factory"]
        lines.extend([
            f"        public static {quantity_type}<T> {factory_name}<T>(T value) where T : IFloatingPoint<T>",
            f"            => {quantity_type}<T>.{factory_name}(value);",
            "",
            f"        public static T To{property_name}<T>(this {quantity_type}<T> quantity) where T : IFloatingPoint<T>",
            f"            => quantity.{property_name};",
            "",
        ])

    if lines[-1] == "":
        lines.pop()
    lines.extend([
        "    }",
        "}",
        "#endif",
        "",
    ])
    return "\n".join(lines)

def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()

    model = json.loads(DEFINITIONS.read_text(encoding="utf-8"))
    expected = {
        OUTPUT_DIR / (family_name + "Methods.Generated.cs"): render_family(family_name, family)
        for family_name, family in model["families"].items()
    }

    if args.check:
        actual = set(OUTPUT_DIR.glob("*Methods.Generated.cs")) if OUTPUT_DIR.exists() else set()
        if actual != set(expected):
            raise SystemExit("Generated quantity API file set is out of date. Run scripts/generate_quantity_api.py")
        for path, generated in expected.items():
            if path.read_text(encoding="utf-8") != generated:
                raise SystemExit("Generated quantity API is out of date. Run scripts/generate_quantity_api.py")
        print("Generated quantity API is up to date.")
        return

    OUTPUT_DIR.mkdir(parents=True, exist_ok=True)
    for stale in OUTPUT_DIR.glob("*Methods.Generated.cs"):
        if stale not in expected:
            stale.unlink()
    for path, generated in expected.items():
        path.write_text(generated, encoding="utf-8")
        print("Wrote", path.relative_to(ROOT))

if __name__ == "__main__":
    main()
